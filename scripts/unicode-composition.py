#!/usr/bin/env python3
"""Writes engine/src/Lockflight.Cli/Paths/UnicodeCompositionData.cs from Python's Unicode database.

The engine runs with invariant globalization, where string.Normalize does nothing, so it carries the canonical composition
pairs and combining classes it needs to compare path names in NFC. Run it when Python's Unicode version moves on:

    python3 scripts/unicode-composition.py > engine/src/Lockflight.Cli/Paths/UnicodeCompositionData.cs
"""
import unicodedata

PER_LINE = 6


def compositions():
    """(first, second, composed) for every canonical pair NFC recomposes; Hangul syllables are composed by formula."""
    for code in range(0x110000):
        decomposition = unicodedata.decomposition(chr(code))
        if not decomposition or decomposition.startswith("<"):
            continue
        parts = [int(part, 16) for part in decomposition.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(code):
            yield (parts[0], parts[1], code)


def combining_classes():
    """[first, last, class] ranges of code points with a non-zero canonical combining class."""
    ranges = []
    for code in range(0x110000):
        value = unicodedata.combining(chr(code))
        if not value:
            continue
        if ranges and ranges[-1][1] == code - 1 and ranges[-1][2] == value:
            ranges[-1][1] = code
        else:
            ranges.append([code, code, value])
    return ranges


def rows(triples, third_in_hex=True):
    items = [f"0x{a:X}, 0x{b:X}, " + (f"0x{c:X}" if third_in_hex else str(c)) for a, b, c in triples]
    for start in range(0, len(items), PER_LINE):
        yield "        " + ", ".join(items[start:start + PER_LINE]) + ","


PAIRS = list(compositions())
CLASSES = combining_classes()

print(f"""namespace Lockflight.Cli.Paths;

/// <summary>
/// Unicode {unicodedata.unidata_version} data for <see cref="UnicodeNormalization"/>, generated by <c>scripts/unicode-composition.py</c>; do
/// not edit by hand.
/// </summary>
internal static class UnicodeCompositionData
{{
    /// <summary>Triples of first code point, second code point and the code point NFC composes them to.</summary>
    public static ReadOnlySpan<int> Compositions =>
    [""")
for line in rows(PAIRS):
    print(line)
print("""    ];

    /// <summary>Triples of first and last code point of a range and its canonical combining class (non-zero ones only).</summary>
    public static ReadOnlySpan<int> CombiningClasses =>
    [""")
for line in rows(CLASSES, third_in_hex=False):
    print(line)
print("""    ];
}""")
