using System.Globalization;
using System.Text;
using Lockflight.Cli.Config;

namespace Lockflight.Cli.Workspace;

/// <summary>
/// The <c>lockflight.unit.yaml</c> a unit repository's CI judges pull requests with (vendored policy): every shell
/// protected path that can match inside the unit, re-based (<see cref="Rebase"/>), and the gate settings with the unit's own build
/// file and test framework.
/// The first line names the shell commit it came from; the rest is the policy, compared by <c>workspace sync --check</c>.
/// </summary>
internal static class UnitPolicy
{
    public const string HeaderPrefix = "# Generated by `lockflight workspace sync` from the workspace shell";

    public static string Render(Manifest manifest, Unit unit, string shellCommit) =>
        $"{HeaderPrefix} at {shellCommit}. Do not edit: change the shell's lockflight.yaml and run sync.\n" + Body(manifest, unit);

    /// <summary>The policy without the header: what drift is judged on (the commit changes on every shell commit).</summary>
    public static string Body(Manifest manifest, Unit unit)
    {
        string[] globs = [.. manifest.ProtectedGlobs.Select(glob => Rebase(glob, unit.Path)).OfType<string>().Where(glob => glob.Length > 0).Distinct(StringComparer.Ordinal)];
        GateSettings gates = manifest.Gates;
        StringBuilder text = new();
        text.Append("version: 1\n");
        text.Append(globs.Length == 0 ? "protected: []\n" : "protected:\n" + string.Concat(globs.Select(glob => $"  - \"{glob}\"\n")));
        text.Append("gates:\n").Append(CultureInfo.InvariantCulture, $"  timeoutSeconds: {gates.TimeoutSeconds}\n");
        if (unit.Build is string build)
        {
            text.Append(CultureInfo.InvariantCulture, $"  build: {build}\n");
        }

        if ((unit.TestFramework ?? gates.TestFramework) is string framework)
        {
            text.Append("  test:\n").Append(CultureInfo.InvariantCulture, $"    framework: {framework}\n");
        }

        string collector = gates.Coverage.Collector switch { CoverageCollector.Coverlet => "coverlet", CoverageCollector.Microsoft => "microsoft", _ => "none" };
        text.Append("  coverage:\n")
            .Append(CultureInfo.InvariantCulture, $"    collector: {collector}\n")
            .Append(CultureInfo.InvariantCulture, $"    patchThreshold: {gates.Coverage.PatchThreshold}\n")
            .Append(CultureInfo.InvariantCulture, $"    minChangedLines: {gates.Coverage.MinChangedLines}\n");
        return text.ToString();
    }

    /// <summary>
    /// A shell glob as seen from inside the unit, or null when it cannot match there. Segments are matched against the unit's
    /// path one by one (<c>*</c> and <c>?</c> within a segment); a <c>**</c> segment reached before the unit path is used up can
    /// match at any depth inside the unit, so the rest is kept under <c>**/</c> — wider, never narrower, than the shell's rule.
    /// </summary>
    public static string? Rebase(string glob, string unitPath)
    {
        string[] pattern = glob.Split('/');
        string[] unit = unitPath.Split('/');
        for (int index = 0; index < pattern.Length; index++)
        {
            if (pattern[index] == "**")
            {
                return "**/" + string.Join('/', pattern.Skip(index + 1));
            }

            if (index == unit.Length)
            {
                return string.Join('/', pattern.Skip(index));
            }

            if (!SegmentMatches(pattern[index], unit[index]))
            {
                return null;
            }
        }

        // The glob names the unit directory itself (or less): it covers the whole unit.
        return pattern.Length == unit.Length ? "**" : null;
    }

    private static bool SegmentMatches(string pattern, string segment) =>
        System.Text.RegularExpressions.Regex.IsMatch(
            segment,
            "^" + System.Text.RegularExpressions.Regex.Escape(pattern).Replace("\\*", "[^/]*", StringComparison.Ordinal).Replace("\\?", "[^/]", StringComparison.Ordinal) + "$",
            System.Text.RegularExpressions.RegexOptions.IgnoreCase | System.Text.RegularExpressions.RegexOptions.CultureInvariant,
            TimeSpan.FromSeconds(1));

    /// <summary>A vendored file without its header line.</summary>
    public static string BodyOf(string vendored)
    {
        int newline = vendored.IndexOf('\n', StringComparison.Ordinal);
        return vendored.StartsWith(HeaderPrefix, StringComparison.Ordinal) && newline >= 0 ? vendored[(newline + 1)..] : vendored;
    }
}
