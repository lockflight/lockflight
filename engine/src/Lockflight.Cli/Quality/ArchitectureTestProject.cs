using System.Text;
using System.Text.RegularExpressions;
using Lockflight.Cli.Gates;
using Lockflight.Cli.Projects;

namespace Lockflight.Cli.Quality;

/// <summary>
/// The architecture test project <c>init --architecture-tests</c> writes: one test per layer that may not depend on the layers
/// after it (Domain → Application → Infrastructure → Api), with ArchUnitNET (Apache-2.0, actively maintained; NetArchTest has
/// had no release since 2021). The layers are the projects whose names end in <c>.Domain</c>, <c>.Application</c>,
/// <c>.Infrastructure</c> and <c>.Api</c> (or <c>.WebApi</c>); the test reads their assemblies.
/// </summary>
internal static partial class ArchitectureTestProject
{
    public const string ArchUnitPackage = "TngTech.ArchUnitNET.xUnitV3";
    public const string ArchUnitVersion = "0.13.4";
    public const string TestFileName = "LayerDependencyTests.cs";
    public const string CentralPackagesFile = "Directory.Packages.props";

    private const string ProjectSuffix = "ArchitectureTests";
    private const string DefaultFramework = "net10.0";

    private static readonly (string Package, string Version)[] VSTestPackages =
    [
        ("Microsoft.NET.Test.Sdk", "18.10.1"),
        (ArchUnitPackage, ArchUnitVersion),
        ("xunit.v3.mtp-off", "4.0.2"),
        ("xunit.runner.visualstudio", "4.0.1"),
    ];

    private static readonly (string Package, string Version)[] TestingPlatformPackages =
    [
        (ArchUnitPackage, ArchUnitVersion),
        ("xunit.v3.mtp-v2", "4.0.2"),
    ];

    /// <summary>The layer projects under the root, inner layer first; test projects are not layers.</summary>
    public static IReadOnlyList<LayerProject> Layers(string root)
    {
        HashSet<string> testProjects = [.. ProjectFiles.TestProjects(root)];
        List<LayerProject> layers = [];
        foreach (string project in ProjectFiles.All(root).Where(project => !testProjects.Contains(project)))
        {
            if (LayerOf(Path.GetFileNameWithoutExtension(project)) is ArchitectureLayer layer)
            {
                layers.Add(new LayerProject(layer, Path.GetRelativePath(root, project).Replace('\\', '/'), AssemblyName(project)));
            }
        }

        return [.. layers.OrderBy(layer => layer.Layer).ThenBy(layer => layer.RelativePath, StringComparer.Ordinal)];
    }

    /// <summary>Why no test can be generated (fewer than two layers, so there is no dependency to check); null when one can.</summary>
    public static string? Problem(IReadOnlyList<LayerProject> layers) =>
        layers.Select(layer => layer.Layer).Distinct().Count() < 2
            ? "--architecture-tests found fewer than two layer projects (names ending in .Domain, .Application, .Infrastructure, .Api or .WebApi), so there is no dependency between layers to test; write the test by hand (docs/guides/code-quality.md shows one)"
            : null;

    /// <summary>The test project's directory, relative to the root: under <c>tests/</c>, or <c>test/</c> when only that exists.</summary>
    public static string RelativeDirectory(string root, IReadOnlyList<LayerProject> layers)
    {
        string parent = !Directory.Exists(Path.Combine(root, "tests")) && Directory.Exists(Path.Combine(root, "test")) ? "test" : "tests";
        return $"{parent}/{Name(layers)}";
    }

    /// <summary>The project's name: the layers' common prefix and <c>ArchitectureTests</c> (never <c>Architecture</c>, ArchUnitNET's type).</summary>
    public static string Name(IReadOnlyList<LayerProject> layers)
    {
        string first = Path.GetFileNameWithoutExtension(layers[0].RelativePath);
        int dot = first.LastIndexOf('.');
        return dot > 0 ? $"{first[..dot]}.{ProjectSuffix}" : ProjectSuffix;
    }

    /// <summary>Whether the repository pins package versions centrally, so a project's references carry no version.</summary>
    public static bool UsesCentralPackages(string root)
    {
        string path = Path.Combine(root, CentralPackagesFile);
        return File.Exists(path) && CentralManagementOn().IsMatch(File.ReadAllText(path));
    }

    /// <summary>The test project file; versions are left to <c>Directory.Packages.props</c> when the repository pins them there.</summary>
    public static string ProjectFile(string root, string directory, IReadOnlyList<LayerProject> layers, bool centralPackages)
    {
        StringBuilder project = new();
        project.Append("<Project Sdk=\"Microsoft.NET.Sdk\">\n")
            .Append($"  <!-- Generated by lockflight init (architecture tests): the layers may depend only inward. See {TestFileName}. -->\n")
            .Append("  <PropertyGroup>\n")
            .Append($"    <TargetFramework>{Framework(root, layers)}</TargetFramework>\n")
            .Append("    <OutputType>Exe</OutputType>\n")
            .Append("    <ImplicitUsings>enable</ImplicitUsings>\n")
            .Append("    <Nullable>enable</Nullable>\n")
            .Append("    <IsPackable>false</IsPackable>\n")
            .Append("  </PropertyGroup>\n")
            .Append("  <ItemGroup>\n");
        foreach ((string package, string version) in Packages(root))
        {
            project.Append(centralPackages ? $"    <PackageReference Include=\"{package}\" />\n" : $"    <PackageReference Include=\"{package}\" Version=\"{version}\" />\n");
        }

        project.Append("  </ItemGroup>\n").Append("  <ItemGroup>\n");
        foreach (LayerProject layer in layers)
        {
            string relative = Path.GetRelativePath(Path.Combine(root, directory), Path.Combine(root, layer.RelativePath)).Replace('\\', '/');
            project.Append($"    <ProjectReference Include=\"{relative}\" />\n");
        }

        return project.Append("  </ItemGroup>\n").Append("</Project>\n").ToString();
    }

    /// <summary>
    /// <c>Directory.Packages.props</c> with a <c>PackageVersion</c> for each test package it lacks; null when it has them all or
    /// has no closing <c>&lt;/Project&gt;</c>.
    /// </summary>
    public static string? CentralPackages(string root, string existing)
    {
        string[] missing = [.. Packages(root).Where(entry => !existing.Contains($"\"{entry.Package}\"", StringComparison.OrdinalIgnoreCase))
            .Select(entry => $"    <PackageVersion Include=\"{entry.Package}\" Version=\"{entry.Version}\" />")];
        int end = existing.LastIndexOf("</Project>", StringComparison.Ordinal);
        return missing.Length == 0 || end < 0
            ? null
            : existing[..end] + "  <!-- The architecture tests generated by lockflight init. -->\n  <ItemGroup>\n" + string.Join('\n', missing) + "\n  </ItemGroup>\n" + existing[end..];
    }

    /// <summary>The test class: one assembly field and one type set per layer, and one test per layer that has an outer layer.</summary>
    public static string TestFile(IReadOnlyList<LayerProject> layers)
    {
        ArchitectureLayer[] present = [.. layers.Select(layer => layer.Layer).Distinct().Order()];
        StringBuilder test = new();
        test.Append("""
            using ArchUnitNET.Domain;
            using ArchUnitNET.Fluent;
            using ArchUnitNET.Loader;
            using ArchUnitNET.xUnitV3;
            using Xunit;
            using static ArchUnitNET.Fluent.ArchRuleDefinition;
            using ReflectionAssembly = System.Reflection.Assembly;

            """).Append($"\nnamespace {Name(layers)};\n\n").Append("""
            /// <summary>
            /// Generated by `lockflight init --architecture-tests`: each layer may depend only on the layers inside it
            /// (Domain, then Application, then Infrastructure, then Api). Edit the layers to match the solution; a person reviews
            /// any change that loosens a rule.
            /// </summary>
            public sealed class LayerDependencyTests
            {

            """);
        for (int index = 0; index < layers.Count; index++)
        {
            test.Append($"    private static readonly ReflectionAssembly {AssemblyField(layers, index)} = ReflectionAssembly.Load(\"{layers[index].AssemblyName}\");\n");
        }

        test.Append($"\n    private static readonly Architecture Architecture = new ArchLoader().LoadAssemblies({string.Join(", ", layers.Select((_, index) => AssemblyField(layers, index)))}).Build();\n\n");
        foreach (ArchitectureLayer layer in present)
        {
            string[] assemblies = [.. layers.Select((project, index) => (project, index)).Where(entry => entry.project.Layer == layer).Select(entry => $"ResideInAssembly({AssemblyField(layers, entry.index)})")];
            test.Append($"    private static readonly IObjectProvider<IType> {LayerName(layer)} = Types().That().{string.Join(".Or().", assemblies)}.As(\"{LayerName(layer)}\");\n");
        }

        foreach (ArchitectureLayer layer in present)
        {
            ArchitectureLayer[] outer = [.. present.Where(other => other > layer)];
            if (outer.Length == 0)
            {
                continue;
            }

            string forbidden = outer.Length == 1 ? LayerName(outer[0]) : "Types().That()." + string.Join(".Or().", outer.Select(other => $"Are({LayerName(other)})"));
            test.Append($"\n    [Fact]\n    public void {LayerName(layer)}DependsOnNoOuterLayer() =>\n        Types().That().Are({LayerName(layer)}).Should().NotDependOnAny({forbidden}).Check(Architecture);\n");
        }

        return test.Append("}\n").ToString();
    }

    /// <summary>The layer's name in the generated code: its type set, its test and its assembly fields.</summary>
    public static string LayerName(ArchitectureLayer layer) => layer switch
    {
        ArchitectureLayer.Domain => "Domain",
        ArchitectureLayer.Application => "Application",
        ArchitectureLayer.Infrastructure => "Infrastructure",
        _ => "Api",
    };

    private static ArchitectureLayer? LayerOf(string projectName)
    {
        string last = projectName[(projectName.LastIndexOf('.') + 1)..];
        return last.ToUpperInvariant() switch
        {
            "DOMAIN" => ArchitectureLayer.Domain,
            "APPLICATION" => ArchitectureLayer.Application,
            "INFRASTRUCTURE" => ArchitectureLayer.Infrastructure,
            "API" or "WEBAPI" => ArchitectureLayer.Api,
            _ => null,
        };
    }

    /// <summary>The project's literal <c>AssemblyName</c>, else its file name, as MSBuild defaults it.</summary>
    private static string AssemblyName(string projectPath) =>
        AssemblyNameElement().Match(File.ReadAllText(projectPath)) is { Success: true } match && !match.Groups["name"].Value.Contains("$(", StringComparison.Ordinal)
            ? match.Groups["name"].Value.Trim()
            : Path.GetFileNameWithoutExtension(projectPath);

    /// <summary>A field name per layer project: <c>DomainAssembly</c>, or <c>DomainAssembly2</c> for a second Domain project.</summary>
    private static string AssemblyField(IReadOnlyList<LayerProject> layers, int index)
    {
        int ordinal = layers.Take(index).Count(earlier => earlier.Layer == layers[index].Layer);
        string name = LayerName(layers[index].Layer);
        return ordinal == 0 ? $"{name}Assembly" : $"{name}Assembly{ordinal + 1}";
    }


    /// <summary>The newest modern target any layer builds for, so the test can load every layer; net10.0 when none says.</summary>
    private static string Framework(string root, IReadOnlyList<LayerProject> layers) =>
        layers.SelectMany(layer => ProjectFiles.TargetFrameworks(root, Path.Combine(root, layer.RelativePath)))
            .Select(framework => ModernFramework().Match(framework))
            .Where(match => match.Success)
            .OrderByDescending(match => new Version(match.Groups["version"].Value))
            .Select(match => match.Value)
            .FirstOrDefault() ?? DefaultFramework;

    private static (string Package, string Version)[] Packages(string root) =>
        TestRunnerDetection.For(root) == TestRunnerKind.MicrosoftTestingPlatform ? TestingPlatformPackages : VSTestPackages;

    [GeneratedRegex(@"<AssemblyName>(?<name>[^<]+)</AssemblyName>", RegexOptions.IgnoreCase)]
    private static partial Regex AssemblyNameElement();

    [GeneratedRegex(@"^net(?<version>\d+\.\d+)$", RegexOptions.IgnoreCase)]
    private static partial Regex ModernFramework();

    [GeneratedRegex(@"<ManagePackageVersionsCentrally>\s*true\s*</ManagePackageVersionsCentrally>", RegexOptions.IgnoreCase)]
    private static partial Regex CentralManagementOn();
}
