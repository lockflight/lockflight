namespace Lockflight.Cli.Init;

/// <summary>
/// The GitLab CI/CD job <c>init --ci-platform gitlab</c> writes: a file of its own that <c>.gitlab-ci.yml</c> includes, so a
/// team's existing pipeline file is never overwritten.
/// </summary>
internal static class GitLabCiTemplate
{
    public const string Path = ".gitlab/ci/lockflight-gates.yml";
    public const string RootPath = ".gitlab-ci.yml";

    /// <summary>The <c>include</c> entry <c>.gitlab-ci.yml</c> needs, as YAML.</summary>
    public const string Include = $"""
        include:
          - local: /{Path}
        """;

    private const int ScriptIndent = 6;

    private const string FindBase = """
        PULL_REQUEST=""
        case "$CI_PIPELINE_SOURCE" in
          merge_request_event)
            # Policy comes from the target branch's tip, not the merge request's diff base: a branch cut from an old commit must
            # not bring an older engine pin, baselines or analyzer config. The gates work out the merge base themselves.
            PULL_REQUEST=1
            git fetch --quiet origin "+refs/heads/$CI_MERGE_REQUEST_TARGET_BRANCH_NAME:refs/remotes/origin/$CI_MERGE_REQUEST_TARGET_BRANCH_NAME"
            BASE=$(git rev-parse "origin/$CI_MERGE_REQUEST_TARGET_BRANCH_NAME") ;;
          push) BASE="$CI_COMMIT_BEFORE_SHA" ;;
          *) BASE="" ;;
        esac
        """;

    private const string PullRequestRules = """
          rules:
            - if: $CI_PIPELINE_SOURCE == "merge_request_event"
            - if: $CI_PIPELINE_SOURCE == "push" && $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH
        """;

    private const string ManualRules = """
          # Runs only when started by hand (Build → Pipelines → Run pipeline), written by `lockflight init --ci manual`. To judge
          # every merge request, replace these rules with merge_request_event and push-to-the-default-branch rules.
          rules:
            - if: $CI_PIPELINE_SOURCE == "web"
        """;

    private const string PreviewRules = """
          # CI during the preview: this project pins a development build of the engine (built from source by
          # scripts/dev-install.sh), which no package feed has, so the engine install below cannot pass yet and `lockflight init`
          # made this job run only when started by hand. Once the project pins a published release, replace these rules with
          # merge_request_event and push-to-the-default-branch rules.
          rules:
            - if: $CI_PIPELINE_SOURCE == "web"
        """;

    private const string Template = """
        # Lockflight gates for GitLab CI/CD — generated by `lockflight init --ci-platform gitlab`, included from .gitlab-ci.yml:
        #   include:
        #     - local: /{Path}
        # The engine version and policy come from the target branch's tip, so an MR cannot loosen the checks that judge
        # it. Turn on "Pipelines must succeed" and route this file and .gitlab-ci.yml to a code owner. Not yet verified on a live
        # GitLab instance: check the first run. See docs/guides/ci-other-platforms.md in the Lockflight repository.
        lockflight-gates:
          stage: test
          image: {SdkImage}
          variables:
            GIT_DEPTH: "0"
        {Rules}
          script:
            - |
        {Script}
          artifacts:
            when: always
            paths:
              - {ResultDirectory}/

        """;

    private const string RootTemplate = """
        # GitLab CI/CD — written by `lockflight init --ci-platform gitlab`. The Lockflight gates job lives in its own file; add your
        # own jobs here.
        {Include}

        """;

    /// <summary>The included job with its rules; the SDK image gets every other .NET channel given.</summary>
    public static string Job(IReadOnlyList<string> dotnetChannels, CiTrigger trigger, bool developmentPin) =>
        Template
            .Replace("{Path}", Path, StringComparison.Ordinal)
            .Replace("{SdkImage}", CiShellScripts.SdkImage, StringComparison.Ordinal)
            .Replace("{Rules}", Rules(trigger, developmentPin), StringComparison.Ordinal)
            .Replace("{Script}", CiShellScripts.Indent(CiShellScripts.ContainerJob(FindBase, dotnetChannels), ScriptIndent), StringComparison.Ordinal)
            .Replace("{ResultDirectory}", CiShellScripts.ResultDirectory, StringComparison.Ordinal);

    /// <summary>The <c>.gitlab-ci.yml</c> written when the repository has none: only the include.</summary>
    public static string Root() => RootTemplate.Replace("{Include}", Include, StringComparison.Ordinal);

    /// <summary>Whether an existing <c>.gitlab-ci.yml</c> already names the job's file (in an include, presumably).</summary>
    public static bool IsIncludedBy(string rootPipeline) => rootPipeline.Contains(Path, StringComparison.Ordinal);

    private static string Rules(CiTrigger trigger, bool developmentPin) => trigger switch
    {
        CiTrigger.Manual when developmentPin => PreviewRules,
        CiTrigger.Manual => ManualRules,
        _ => PullRequestRules,
    };
}
