    public static IReadOnlyList<string> GitIgnoreEntries { get; } = [".lockflight/bin/", ".lockflight/ledger/", ".lockflight/local/", ".lockflight/backup/", ".lockflight/adopt/", ".claude/worktrees/"];

    /// <summary>The manifest <c>init</c> writes, with the stop-gate comment of the chosen profile.</summary>
    public static string Manifest(InitProfile profile) =>
        ManifestTemplate.Replace(ProfilePlaceholder, profile == InitProfile.Standard ? StandardStopGateNote : LiteStopGateNote, StringComparison.Ordinal);

    /// <summary>The CI workflow; setup-dotnet installs every channel given (a YAML block list when there are several).</summary>
    public static string Workflow(IReadOnlyList<string> dotnetChannels) => Workflow(dotnetChannels, CiTrigger.PullRequest, developmentPin: false);

    /// <summary>
    /// The CI workflow with its trigger: <see cref="CiTrigger.Manual"/> runs only when started by hand, and its comment says why —
    /// the option, or, with <paramref name="developmentPin"/>, an engine pin that no package feed has.
    /// </summary>
    public static string Workflow(IReadOnlyList<string> dotnetChannels, CiTrigger trigger, bool developmentPin)
    {
        string workflow = WithChannels(WorkflowTemplate, dotnetChannels);
        return trigger == CiTrigger.Manual
            ? workflow.Replace(PullRequestTrigger, developmentPin ? PreviewTrigger : ManualTrigger, StringComparison.Ordinal)
            : workflow;
    }

    /// <summary>The unit repository workflow; setup-dotnet installs every channel given.</summary>
    public static string UnitWorkflow(IReadOnlyList<string> dotnetChannels) => WithChannels(UnitWorkflowTemplate, dotnetChannels);

    private static string WithChannels(string template, IReadOnlyList<string> dotnetChannels) =>
        template.Replace(
            DotnetVersionsPlaceholder,
            dotnetChannels.Count == 1 ? dotnetChannels[0] : "|\n" + string.Join('\n', dotnetChannels.Select(channel => DotnetVersionIndent + channel)),
            StringComparison.Ordinal);
}
