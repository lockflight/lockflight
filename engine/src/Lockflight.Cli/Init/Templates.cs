namespace Lockflight.Cli.Init;

/// <summary>File contents <c>lockflight init</c> writes when a file does not exist yet.</summary>
internal static class Templates
{
    public const string MarketplaceName = "lockflight";
    public const string MarketplaceRepository = "lockflight/lockflight";
    public const string PluginId = "lockflight@lockflight";
    public const string WorkflowPath = ".github/workflows/lockflight-gates.yml";

    private const string DotnetVersionsPlaceholder = "{DotnetVersions}";
    private const string DotnetVersionIndent = "            ";

    private const string ProfilePlaceholder = "{StopGateNote}";

    private const string PullRequestTrigger = """
        on:
          pull_request:
          push:
            branches: [main]
        """;

    private const string ManualTrigger = """
        # Runs only when started by hand (Actions → lockflight-gates → Run workflow), written by `lockflight init --ci manual`.
        # To judge every pull request, replace this block with the pull_request and push (branches: [main]) triggers.
        on:
          workflow_dispatch:
        """;

    private const string PreviewTrigger = """
        # CI during the preview: this project pins a development build of the engine (built from source by
        # scripts/dev-install.sh), which no package feed has, so the engine install below cannot pass yet and `lockflight init`
        # made this workflow run only when started by hand (Actions → lockflight-gates → Run workflow). Once the project pins a
        # published release, replace this block with the pull_request and push (branches: [main]) triggers.
        on:
          workflow_dispatch:
        """;

    private const string ManifestTemplate = """
        # Lockflight project manifest — https://github.com/lockflight/lockflight
        # Built-in protected paths always apply: this file, the tool pin, .lockflight/, Claude settings, .NET build-control files
        # (Directory.Build.*, Directory.Packages.props, global.json, NuGet.config), code-style and analyzer policy (.editorconfig,
        # .globalconfig, *.ruleset, stylecop.json, BannedSymbols.txt), .gitattributes, gitleaks policy and the Lockflight CI workflow.
        # The full list: https://github.com/lockflight/lockflight/blob/main/docs/guides/configuration.md
        version: 1

        # Extra paths the agent must not change.
        protected: []

        # Stop gate: run build + tests when the agent ends a turn (at most 540 s, below the plugin's Stop hook timeout).
        {StopGateNote}
        stop:
          gate: false
          target: .

        """;

    private const string LiteStopGateNote = "# Off in the lite profile; turn it on once you know how long your build and tests take.";

    private const string StandardStopGateNote =
        "# Off at first in the standard profile too: turn it on once you know how long your build and tests take and the\n" +
        "# known-failing tests are accepted (a person runs '.lockflight/bin/lockflight baseline tests').";

    private const string WorkflowTemplate = """
        # Lockflight gates — generated by `lockflight init`. The engine version and policy come from the base branch on pull
        # requests, so a PR cannot loosen the checks that judge it. Protected files a PR changes are listed in the step summary;
        # route them to a human with CODEOWNERS (see the Lockflight docs). The engine is installed outside the repository's
        # global.json (which may pin an SDK older than 10), from nuget.org or the package sources in the repository's nuget.config.
        name: lockflight-gates

        on:
          pull_request:
          push:
            branches: [main]

        permissions:
          contents: read

        env:
          GITLEAKS_VERSION: 8.30.1
          GITLEAKS_SHA256: 551f6fc83ea457d62a0d98237cbad105af8d557003051f41f3e7ca7b3f2470eb

        jobs:
          gates:
            runs-on: ubuntu-latest
            steps:
              - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
                with:
                  fetch-depth: 0
              - name: Use the base branch's engine pin and policy
                if: github.event_name == 'pull_request'
                env:
                  BASE: ${{ github.event.pull_request.base.sha }}
                run: |
                  for file in dotnet-tools.json .config/dotnet-tools.json lockflight.yaml .gitleaks.toml .gitleaksignore nuget.config NuGet.config; do
                    if git cat-file -e "$BASE:$file" 2>/dev/null; then git checkout "$BASE" -- "$file"; else rm -f "$file"; fi
                  done
                  # Accepted baselines (known-failing tests, warnings, advisories) are policy too: a PR cannot accept its own failures.
                  rm -rf .lockflight/baselines
                  if git cat-file -e "$BASE:.lockflight/baselines" 2>/dev/null; then git checkout "$BASE" -- .lockflight/baselines; fi
                  # Code-style and analyzer config (nested files too) decides what the build and format gates enforce: a PR is
                  # judged by the base's rules, and its own rule changes apply after the merge.
                  style='(^|/)(\.editorconfig|\.globalconfig|[^/]*\.globalconfig|[^/]*\.ruleset|stylecop\.json|BannedSymbols\.txt)$'
                  { git ls-tree -r --name-only "$BASE"; git ls-files; } | grep -E "$style" | sort -u | while IFS= read -r file; do
                    if git cat-file -e "$BASE:$file" 2>/dev/null; then git checkout "$BASE" -- "$file"; else rm -f "$file"; fi
                  done
              - name: Install gitleaks (pinned, checksum-verified)
                run: |
                  archive="gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz"
                  curl -fsSLo "$RUNNER_TEMP/$archive" "https://github.com/gitleaks/gitleaks/releases/download/v${GITLEAKS_VERSION}/$archive"
                  echo "$GITLEAKS_SHA256  $RUNNER_TEMP/$archive" | sha256sum -c -
                  tar -xzf "$RUNNER_TEMP/$archive" -C "$RUNNER_TEMP" gitleaks
                  echo "LOCKFLIGHT_GITLEAKS=$RUNNER_TEMP/gitleaks" >> "$GITHUB_ENV"
              - uses: actions/setup-dotnet@a98b56852c35b8e3190ac28c8c2271da59106c68 # v6.0.0
                with:
                  dotnet-version: {DotnetVersions}
              - name: Install the pinned engine (outside the repository's global.json)
                run: |
                  manifest=$(ls dotnet-tools.json .config/dotnet-tools.json 2>/dev/null | head -n 1)
                  version=$(python3 -c 'import json, sys; print(json.load(open(sys.argv[1]))["tools"]["lockflight.cli"]["version"])' "$manifest")
                  config=()
                  for file in nuget.config NuGet.config; do [ -f "$file" ] && config=(--configfile "$PWD/$file"); done
                  (cd "$RUNNER_TEMP" && dotnet tool install Lockflight.Cli --tool-path "$RUNNER_TEMP/lockflight" --version "$version" "${config[@]}")
                  echo "$RUNNER_TEMP/lockflight" >> "$GITHUB_PATH"
              - name: Gates
                env:
                  BASE: ${{ github.event_name == 'pull_request' && github.event.pull_request.base.sha || github.event.before }}
                run: |
                  base_args=()
                  if [ -n "$BASE" ] && git cat-file -e "$BASE^{commit}" 2>/dev/null; then base_args=(--base "$BASE"); fi
                  lockflight gate run --profile pr "${base_args[@]}" --result artifacts/lockflight/result.json | tee -a "$GITHUB_STEP_SUMMARY"
                  exit "${PIPESTATUS[0]}"
              - uses: actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9 # v7.0.2
                if: always()
                with:
                  name: lockflight-result
                  path: artifacts/lockflight/

        """;

