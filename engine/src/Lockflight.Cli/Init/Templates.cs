    /// <summary>
    /// The CI workflow <c>workspace sync</c> writes into a unit repository: the same base-branch rules as the project
    /// workflow, with the vendored <c>lockflight.unit.yaml</c> as the policy, and the engine installed outside the repository's
    /// <c>global.json</c> — an SDK pin older than 10 cannot restore it — and run directly.
    /// </summary>
    private const string UnitWorkflowTemplate = """
        # Lockflight gates for a unit repository — generated by `lockflight workspace sync` in the workspace shell. The policy
        # (lockflight.unit.yaml), the engine pin and the baselines come from the base branch on pull requests, so a PR cannot
        # loosen the checks that judge it. Route changes to them to a human with CODEOWNERS.
        name: lockflight-gates

        on:
          pull_request:
          push:
            branches: [main]

        permissions:
          contents: read

        env:
          GITLEAKS_VERSION: 8.30.1
          GITLEAKS_SHA256: 551f6fc83ea457d62a0d98237cbad105af8d557003051f41f3e7ca7b3f2470eb

        jobs:
          gates:
            runs-on: ubuntu-latest
            steps:
              - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
                with:
                  fetch-depth: 0
              - name: Use the base branch's engine pin and policy
                if: github.event_name == 'pull_request'
                env:
                  BASE: ${{ github.event.pull_request.base.sha }}
                run: |
                  for file in dotnet-tools.json .config/dotnet-tools.json lockflight.unit.yaml .gitleaks.toml .gitleaksignore nuget.config NuGet.config NuGet.Config; do
                    if git cat-file -e "$BASE:$file" 2>/dev/null; then git checkout "$BASE" -- "$file"; else rm -f "$file"; fi
                  done
                  rm -rf .lockflight/baselines
                  if git cat-file -e "$BASE:.lockflight/baselines" 2>/dev/null; then git checkout "$BASE" -- .lockflight/baselines; fi
                  style='(^|/)(\.editorconfig|\.globalconfig|[^/]*\.globalconfig|[^/]*\.ruleset|stylecop\.json|BannedSymbols\.txt|CodeMetricsConfig\.txt)$'
                  { git ls-tree -r --name-only "$BASE"; git ls-files; } | grep -E "$style" | sort -u | while IFS= read -r file; do
                    if git cat-file -e "$BASE:$file" 2>/dev/null; then git checkout "$BASE" -- "$file"; else rm -f "$file"; fi
                  done
              - name: Install gitleaks (pinned, checksum-verified)
                run: |
                  archive="gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz"
                  curl -fsSLo "$RUNNER_TEMP/$archive" "https://github.com/gitleaks/gitleaks/releases/download/v${GITLEAKS_VERSION}/$archive"
                  echo "$GITLEAKS_SHA256  $RUNNER_TEMP/$archive" | sha256sum -c -
                  tar -xzf "$RUNNER_TEMP/$archive" -C "$RUNNER_TEMP" gitleaks
                  echo "LOCKFLIGHT_GITLEAKS=$RUNNER_TEMP/gitleaks" >> "$GITHUB_ENV"
              - uses: actions/setup-dotnet@a98b56852c35b8e3190ac28c8c2271da59106c68 # v6.0.0
                with:
                  dotnet-version: {DotnetVersions}
              - name: Install the pinned engine (outside the repository's global.json)
                run: |
                  manifest=$(ls dotnet-tools.json .config/dotnet-tools.json 2>/dev/null | head -n 1)
                  version=$(python3 -c 'import json, sys; print(json.load(open(sys.argv[1]))["tools"]["lockflight.cli"]["version"])' "$manifest")
                  config=()
                  for file in nuget.config NuGet.config NuGet.Config; do [ -f "$file" ] && config=(--configfile "$PWD/$file"); done
                  (cd "$RUNNER_TEMP" && dotnet tool install Lockflight.Cli --tool-path "$RUNNER_TEMP/lockflight" --version "$version" "${config[@]}")
                  echo "$RUNNER_TEMP/lockflight" >> "$GITHUB_PATH"
              - name: Gates
                env:
                  BASE: ${{ github.event_name == 'pull_request' && github.event.pull_request.base.sha || github.event.before }}
                run: |
                  base_args=()
                  if [ -n "$BASE" ] && git cat-file -e "$BASE^{commit}" 2>/dev/null; then base_args=(--base "$BASE"); fi
                  lockflight gate run --profile pr "${base_args[@]}" --result artifacts/lockflight/result.json | tee -a "$GITHUB_STEP_SUMMARY"
                  exit "${PIPESTATUS[0]}"
              - uses: actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9 # v7.0.2
                if: always()
                with:
                  name: lockflight-result
                  path: artifacts/lockflight/

        """;

    public static IReadOnlyList<string> GitIgnoreEntries { get; } = [".lockflight/bin/", ".lockflight/ledger/", ".lockflight/local/", ".claude/worktrees/"];

    /// <summary>
    /// The manifest <c>init</c> writes (version 2), with the stop-gate comment of the chosen profile, the approvals and the routing
    /// preset with every value written down.
    /// </summary>
    public static string Manifest(InitProfile profile, RoutingPreset preset) =>
        ManifestTemplate.Replace(ProfilePlaceholder, profile == InitProfile.Standard ? StandardStopGateNote : LiteStopGateNote, StringComparison.Ordinal)
        + ManifestYaml.Approvals(ApprovalCheckMode.Fail, preset) + "\n" + ManifestYaml.Routing(preset);

    /// <summary>The CI workflow; setup-dotnet installs every channel given (a YAML block list when there are several).</summary>
    public static string Workflow(IReadOnlyList<string> dotnetChannels) => Workflow(dotnetChannels, CiTrigger.PullRequest, developmentPin: false);

    /// <summary>
    /// The CI workflow with its trigger: <see cref="CiTrigger.Manual"/> runs only when started by hand, and its comment says why —
    /// the option, or, with <paramref name="developmentPin"/>, an engine pin that no package feed has.
    /// </summary>
    public static string Workflow(IReadOnlyList<string> dotnetChannels, CiTrigger trigger, bool developmentPin)
    {
        string workflow = WithChannels(WorkflowTemplate, dotnetChannels);
        return trigger == CiTrigger.Manual
            ? workflow.Replace(PullRequestTrigger, developmentPin ? PreviewTrigger : ManualTrigger, StringComparison.Ordinal)
            : workflow;
    }

    /// <summary>The unit repository workflow; setup-dotnet installs every channel given.</summary>
    public static string UnitWorkflow(IReadOnlyList<string> dotnetChannels) => WithChannels(UnitWorkflowTemplate, dotnetChannels);

    /// <summary>The engine install step of the GitHub workflow as Lockflight 0.2 wrote it, which <c>update</c> replaces.</summary>
    public const string LegacyGitHubInstallEngine = """
        manifest=$(ls dotnet-tools.json .config/dotnet-tools.json 2>/dev/null | head -n 1)
        version=$(python3 -c 'import json, sys; print(json.load(open(sys.argv[1]))["tools"]["lockflight.cli"]["version"])' "$manifest")
        config=()
        for file in nuget.config NuGet.config; do [ -f "$file" ] && config=(--configfile "$PWD/$file"); done
        (cd "$RUNNER_TEMP" && dotnet tool install Lockflight.Cli --tool-path "$RUNNER_TEMP/lockflight" --version "$version" "${config[@]}")
        """;

    /// <summary>The indentation of a <c>run: |</c> body in the GitHub workflow.</summary>
    public const int WorkflowScriptIndent = 10;

    private static string WithChannels(string template, IReadOnlyList<string> dotnetChannels) =>
        template.Replace("{ActionReference}", ActionReference, StringComparison.Ordinal)
            .Replace("{ActionCommit}", ActionCommit, StringComparison.Ordinal)
            .Replace("{ActionVersion}", ActionVersion, StringComparison.Ordinal)
            .Replace("{RestorePolicy}", CiShellScripts.Indent(CiShellScripts.RestorePolicy, WorkflowScriptIndent), StringComparison.Ordinal)
            .Replace("{InstallEngine}", CiShellScripts.Indent(CiShellScripts.InstallEngine, WorkflowScriptIndent), StringComparison.Ordinal)
            .Replace(
            DotnetVersionsPlaceholder,
            dotnetChannels.Count == 1 ? dotnetChannels[0] : "|\n" + string.Join('\n', dotnetChannels.Select(channel => DotnetVersionIndent + channel)),
            StringComparison.Ordinal);
}
