namespace Lockflight.Cli.Init;

/// <summary>
/// Moves the GitHub workflow Lockflight 0.2 wrote, which runs the gates in one job, to the CI judge's workflow
/// (<see cref="Templates.Workflow(IReadOnlyList{string}, CiTrigger, bool)"/>). The file is recognised only when it is one of 0.2's
/// templates (<see cref="LegacyGitHubWorkflows"/>) with its .NET channels and trigger, after the edits Lockflight itself makes
/// (<see cref="CiStepMigration"/>: the header, the engine install step between its markers, the policy restore). Any other edit is
/// a person's, so the file is left for a person to move. The replacement keeps the channels, the trigger and the line endings,
/// except that a project pinned to a development build gets the trigger <c>init</c> writes for one (by hand only).
/// </summary>
internal static class JudgeWorkflowMigration
{
    private const string DotnetVersionKey = "dotnet-version:";

    private const string UnitWorkflowMark = "generated by `lockflight workspace sync`";

    /// <summary>
    /// 0.2's triggers and the trigger each keeps. The preview trigger (a development build pinned then) becomes the pull request
    /// trigger once the project pins a release, as <c>init</c> would write it.
    /// </summary>
    private static readonly (string Text, CiTrigger Trigger)[] Triggers =
    [
        (LegacyGitHubWorkflows.PullRequestTrigger, CiTrigger.PullRequest),
        (LegacyGitHubWorkflows.ManualTrigger, CiTrigger.Manual),
        (LegacyGitHubWorkflows.PreviewTrigger, CiTrigger.PullRequest),
    ];

    /// <summary>
    /// Whether the workflow runs the gates alone: it runs <c>lockflight gate run</c> and not the CI judge's action. A unit repository's
    /// workflow, which <c>workspace sync</c> writes and rewrites, runs the gates alone by design and is not counted.
    /// </summary>
    public static bool IsGatesOnly(string text) =>
        text.Contains("lockflight gate run", StringComparison.Ordinal) && !text.Contains("mode: judge", StringComparison.Ordinal)
        && !text.Contains(UnitWorkflowMark, StringComparison.Ordinal);

    /// <param name="developmentPin">
    /// The project pins a development build, which CI cannot install: the replacement then runs only by hand, as <c>init</c> writes it.
    /// </param>
    public static JudgeWorkflowPlan Plan(string text, bool developmentPin)
    {
        if (!IsGatesOnly(text))
        {
            return JudgeWorkflowPlan.NotGatesOnly;
        }

        string newline = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        string lines = text.Replace("\r\n", "\n", StringComparison.Ordinal);
        if (Channels(lines) is not string[] channels)
        {
            return JudgeWorkflowPlan.Edited;
        }

        string normalised = Normalised(lines);
        foreach (string template in LegacyGitHubWorkflows.All)
        {
            foreach ((string trigger, CiTrigger kept) in Triggers)
            {
                string written = WithChannels(template, channels).Replace(LegacyGitHubWorkflows.PullRequestTrigger, trigger, StringComparison.Ordinal);
                if (Normalised(written) == normalised)
                {
                    string replacement = Templates.Workflow(channels, developmentPin ? CiTrigger.Manual : kept, developmentPin);
                    return new JudgeWorkflowPlan(JudgeWorkflowStatus.Recognised, replacement.Replace("\n", newline, StringComparison.Ordinal));
                }
            }
        }

        return JudgeWorkflowPlan.Edited;
    }

    /// <summary>The file as Lockflight's own edits leave it, without trailing blank lines (an editor may add or drop the last newline).</summary>
    private static string Normalised(string text) => (CiStepMigration.Migrate(text) ?? text).TrimEnd('\n');

    /// <summary>The .NET channels of the one <c>dotnet-version:</c>: its value, or the lines of its block list; null when it is not there once.</summary>
    private static string[]? Channels(string text)
    {
        string[] lines = text.Split('\n');
        int[] keys = [.. Enumerable.Range(0, lines.Length).Where(index => lines[index].TrimStart().StartsWith(DotnetVersionKey, StringComparison.Ordinal))];
        if (keys.Length != 1)
        {
            return null;
        }

        string value = lines[keys[0]].TrimStart()[DotnetVersionKey.Length..].Trim();
        if (value != "|")
        {
            return value.Length == 0 ? null : [value];
        }

        string[] channels = [.. lines.Skip(keys[0] + 1)
            .TakeWhile(line => line.StartsWith(LegacyGitHubWorkflows.DotnetVersionIndent, StringComparison.Ordinal) && line.Trim().Length > 0)
            .Select(line => line.Trim())];
        return channels.Length == 0 ? null : channels;
    }

    private static string WithChannels(string template, string[] channels) =>
        template.Replace(
            LegacyGitHubWorkflows.DotnetVersionsPlaceholder,
            channels.Length == 1 ? channels[0] : "|\n" + string.Join('\n', channels.Select(channel => LegacyGitHubWorkflows.DotnetVersionIndent + channel)),
            StringComparison.Ordinal);
}
