namespace Lockflight.Cli.Init;

/// <summary>
/// The CI judge's GitHub workflow as earlier releases wrote it, with the same placeholders as <see cref="Templates"/>
/// (<c>{DotnetVersions}</c>, <c>{ActionReference}</c>). <c>update --project</c> replaces a workflow that is one of these (or the
/// current template), rendered with the file's own .NET channels, trigger, runner and workspace shell, with the current template;
/// any other text is a person's edit and is left alone. A release that changes the template adds the template it replaces here:
/// <c>ReleasedContractTests</c> requires every released version's workflow to be recognised. 0.3.0's needs no entry of its own:
/// the edits <see cref="CiStepMigration"/> makes (the name and the header) turn it into 0.3.1's.
/// </summary>
internal static class ReleasedJudgeWorkflows
{
    /// <summary>
    /// Development builds after 0.3.1: Claude Code installed with <c>npm ci</c> from the action's lockfile; the report jobs took the
    /// policy commit from the judge job's output and downloaded the artifacts by name.
    /// </summary>
    private const string AfterV031 = """
        # Lockflight CI judge — generated by `lockflight init`. Four jobs: `judge` builds and runs the pull request's code with no
        # secret (red at each red commit, green and the pr gates at head, trace); `review` runs the review of record only when the
        # repository variable LOCKFLIGHT_REVIEW is 'true' and the secret ANTHROPIC_API_KEY is set (its key can be reached by the
        # pull request's code: use a spend-limited key scoped to CI); `gates` and `lockflight/judge` read their results as data
        # and set one status context each. `gates` keeps its meaning (the pr gates and green at head); make `lockflight/judge`
        # required when the team produces red commits (a commit with a Lockflight-Red: <n> trailer). The policy, the engine pin
        # (.lockflight/engine.lock) and CODEOWNERS are read from the target branch, not the pull request. The verdict is a strong
        # guardrail, not a boundary: it blocks a merge only where a ruleset or branch protection requires the check. Route
        # .github/workflows/** and .github/actions/** to a code owner: GitHub runs the pull request's own copy of this file.
        # judge's timeout is ci.timeoutMinutes (45) + 10.
        name: lockflight

        on:
          pull_request:
          push:
            branches: [main]

        permissions:
          contents: read

        jobs:
          judge:
            runs-on: ubuntu-latest
            timeout-minutes: 55
            outputs:
              verdict: ${{ steps.judge.outputs.verdict }}
              policy: ${{ steps.judge.outputs.policy }}
            steps:
              - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
                with:
                  ref: ${{ github.event.pull_request.head.sha || github.sha }}
                  fetch-depth: 0
                  persist-credentials: false
              - name: The target branch's tip (fetched now, not the event's)
                id: base
                env:
                  LF_TARGET: ${{ github.base_ref }}
                  LF_BEFORE: ${{ github.event.before }}
                run: |
                  if [ -n "$LF_TARGET" ]; then sha=$(git rev-parse "refs/remotes/origin/$LF_TARGET"); else sha="$LF_BEFORE"; fi
                  echo "sha=$sha" >> "$GITHUB_OUTPUT"
              - uses: actions/setup-dotnet@a98b56852c35b8e3190ac28c8c2271da59106c68 # v6.0.0
                with:
                  dotnet-version: {DotnetVersions}
              - uses: {ActionReference}
                id: judge
                with:
                  mode: judge
                  head: ${{ github.event.pull_request.head.sha || github.sha }}
                  base: ${{ steps.base.outputs.sha }}
                  branch: ${{ github.head_ref }}
                  event: ${{ github.event_name == 'pull_request' && 'pr' || 'push' }}
                  review-expected: ${{ vars.LOCKFLIGHT_REVIEW == 'true' }}

          review:
            needs: judge
            if: ${{ !cancelled() && github.event_name == 'pull_request' && vars.LOCKFLIGHT_REVIEW == 'true' && github.event.pull_request.head.repo.full_name == github.repository && needs.judge.outputs.verdict != 'FAIL' }}
            runs-on: ubuntu-latest
            environment: lockflight-review
            steps:
              - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
                with:
                  ref: ${{ github.event.pull_request.head.sha }}
                  fetch-depth: 0
                  persist-credentials: false
              - name: The target branch's tip
                id: base
                env:
                  LF_TARGET: ${{ github.base_ref }}
                run: echo "sha=$(git rev-parse "refs/remotes/origin/$LF_TARGET")" >> "$GITHUB_OUTPUT"
              - uses: actions/setup-dotnet@a98b56852c35b8e3190ac28c8c2271da59106c68 # v6.0.0
                with:
                  dotnet-version: {DotnetVersions}
              - uses: actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1 # v7.1.0
                with:
                  node-version: 22
              # The action installs Claude Code with npm ci from its own lockfile: every package pinned by version and hash.
              - uses: {ActionReference}
                env:
                  ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}
                with:
                  mode: review
                  head: ${{ github.event.pull_request.head.sha }}
                  base: ${{ steps.base.outputs.sha }}
                  branch: ${{ github.head_ref }}

          gates:
            needs: [judge, review]
            if: ${{ !cancelled() }}
            runs-on: ubuntu-latest
            permissions:
              contents: read
              pull-requests: write
            steps:
              - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
                with:
                  ref: ${{ needs.judge.outputs.policy || github.event.pull_request.base.sha || github.sha }}
                  fetch-depth: 0
                  persist-credentials: false
              - uses: actions/setup-dotnet@a98b56852c35b8e3190ac28c8c2271da59106c68 # v6.0.0
                with:
                  dotnet-version: 10.0.x
              - uses: {ActionReference}
                with:
                  mode: report
                  head: ${{ github.event.pull_request.head.sha || github.sha }}
                  base: ${{ needs.judge.outputs.policy || github.event.pull_request.base.sha || github.sha }}
                  branch: ${{ github.head_ref }}
                  event: ${{ github.event_name == 'pull_request' && 'pr' || 'push' }}
                  replan: "true"
                  context: gates
                  comment: "true"

          judge-report:
            name: lockflight/judge
            needs: [judge, review]
            if: ${{ !cancelled() }}
            runs-on: ubuntu-latest
            steps:
              - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
                with:
                  ref: ${{ needs.judge.outputs.policy || github.event.pull_request.base.sha || github.sha }}
                  fetch-depth: 0
                  persist-credentials: false
              - uses: actions/setup-dotnet@a98b56852c35b8e3190ac28c8c2271da59106c68 # v6.0.0
                with:
                  dotnet-version: 10.0.x
              - uses: {ActionReference}
                with:
                  mode: report
                  head: ${{ github.event.pull_request.head.sha || github.sha }}
                  base: ${{ needs.judge.outputs.policy || github.event.pull_request.base.sha || github.sha }}
                  branch: ${{ github.head_ref }}
                  event: ${{ github.event_name == 'pull_request' && 'pr' || 'push' }}
                  replan: "true"
                  context: lockflight/judge

        """;

