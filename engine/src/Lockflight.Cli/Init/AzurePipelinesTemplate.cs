namespace Lockflight.Cli.Init;

/// <summary>
/// The Azure Pipelines pipeline <c>init --ci-platform azure</c> writes: a pipeline of its own, so the team's
/// <c>azure-pipelines.yml</c> is never touched, made binding as a build validation policy on the target branch.
/// </summary>
internal static class AzurePipelinesTemplate
{
    public const string Path = ".azure-pipelines/lockflight-gates.yml";

    private const int ScriptIndent = 6;

    private const string PullRequestTrigger = """
        # On Azure Repos the pr block is ignored: a build validation policy on main runs this pipeline for every pull request.
        trigger:
          branches:
            include: [main]
        pr:
          branches:
            include: ['*']
        """;

    private const string ManualTrigger = """
        # Runs only when started by hand (Pipelines → Run pipeline), written by `lockflight init --ci manual`. To judge every
        # pull request, replace this block with a trigger on main and a pr block, and add the build validation policy.
        trigger: none
        pr: none
        """;

    private const string PreviewTrigger = """
        # CI during the preview: this project pins a development build of the engine (built from source by
        # scripts/dev-install.sh), which no package feed has, so the engine install below cannot pass yet and `lockflight init`
        # made this pipeline run only when started by hand. Once the project pins a published release, replace this block with
        # a trigger on main and a pr block, and add the build validation policy.
        trigger: none
        pr: none
        """;

    private const string Template = """
        # Lockflight gates for Azure Pipelines — generated by `lockflight init --ci-platform azure`. The policy and the engine pin
        # (.lockflight/engine.lock) are read from the target branch's tip on pull requests, not the pull request. The verdict is a
        # strong guardrail, not a boundary: it blocks a merge only where a build validation policy requires it. Create a pipeline from this
        # file and make it a build validation policy on main; route this file to a required reviewer. Not yet verified on a live
        # Azure DevOps organisation: check the first run. See docs/guides/ci-other-platforms.md in the Lockflight repository.
        {Trigger}

        pool:
          vmImage: ubuntu-latest

        variables:
          GITLEAKS_VERSION: {GitleaksVersion}
          GITLEAKS_SHA256: {GitleaksSha256}

        steps:
          - checkout: self
            fetchDepth: 0
          - bash: |
              set -e
              if [ "$BUILD_REASON" = "PullRequest" ]; then
                # Policy comes from the target branch's tip, not the merge base: a branch cut from an old commit must not bring
                # an older engine pin, baselines or analyzer config. The gates work out the merge base themselves.
                target="${SYSTEM_PULLREQUEST_TARGETBRANCH#refs/heads/}"
                git fetch --quiet origin "+refs/heads/$target:refs/remotes/origin/$target"
                BASE=$(git rev-parse "origin/$target")
              else
                BASE=$(git rev-parse --verify --quiet 'HEAD^' || true)
              fi
              echo "##vso[task.setvariable variable=LOCKFLIGHT_BASE]$BASE"
            displayName: Find the base commit
          - bash: |
              set -e
              BASE="$LOCKFLIGHT_BASE"
        {RestorePolicy}
            displayName: Use the base branch's engine pin and policy
            condition: and(succeeded(), eq(variables['Build.Reason'], 'PullRequest'))
          - bash: |
              set -e
              LOCKFLIGHT_TEMP="$AGENT_TEMPDIRECTORY"
        {InstallGitleaks}
              echo "##vso[task.setvariable variable=LOCKFLIGHT_GITLEAKS]$LOCKFLIGHT_TEMP/gitleaks"
            displayName: Install gitleaks (pinned, checksum-verified)
        {UseDotnet}
          - bash: |
              set -e
              LOCKFLIGHT_TEMP="$AGENT_TEMPDIRECTORY"
        {InstallEngine}
              echo "##vso[task.prependpath]$LOCKFLIGHT_TEMP/lockflight"
            displayName: Install the pinned engine (outside the repository's global.json)
          - bash: |
              set -e
              BASE="$LOCKFLIGHT_BASE"
        {Gates}
            displayName: Gates
          - task: PublishPipelineArtifact@1
            condition: always()
            continueOnError: true
            inputs:
              targetPath: {ResultDirectory}
              artifact: lockflight-result

        """;

    /// <summary>The pipeline with its trigger, installing every .NET channel given with <c>UseDotNet@2</c>.</summary>
    public static string Pipeline(IReadOnlyList<string> dotnetChannels, CiTrigger trigger, bool developmentPin) =>
        Template
            .Replace("{Trigger}", Trigger(trigger, developmentPin), StringComparison.Ordinal)
            .Replace("{GitleaksVersion}", CiShellScripts.GitleaksVersion, StringComparison.Ordinal)
            .Replace("{GitleaksSha256}", CiShellScripts.GitleaksSha256, StringComparison.Ordinal)
            .Replace("{RestorePolicy}", CiShellScripts.Indent(CiShellScripts.RestorePolicy, ScriptIndent), StringComparison.Ordinal)
            .Replace("{InstallGitleaks}", CiShellScripts.Indent(CiShellScripts.InstallGitleaks, ScriptIndent), StringComparison.Ordinal)
            .Replace("{UseDotnet}", string.Join('\n', dotnetChannels.Select(UseDotnet)), StringComparison.Ordinal)
            .Replace("{InstallEngine}", CiShellScripts.Indent(CiShellScripts.InstallEngine, ScriptIndent), StringComparison.Ordinal)
            .Replace("{Gates}", CiShellScripts.Indent(CiShellScripts.Gates, ScriptIndent), StringComparison.Ordinal)
            .Replace("{ResultDirectory}", CiShellScripts.ResultDirectory, StringComparison.Ordinal);

    private static string Trigger(CiTrigger trigger, bool developmentPin) => trigger switch
    {
        CiTrigger.Manual when developmentPin => PreviewTrigger,
        CiTrigger.Manual => ManualTrigger,
        _ => PullRequestTrigger,
    };

    private static string UseDotnet(string channel) => $"""
          - task: UseDotNet@2
            displayName: Install .NET {channel}
            inputs:
              packageType: sdk
              version: {channel}
        """;
}
