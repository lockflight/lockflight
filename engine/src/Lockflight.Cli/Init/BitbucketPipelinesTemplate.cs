namespace Lockflight.Cli.Init;

/// <summary>
/// The Bitbucket Pipelines file <c>init --ci-platform bitbucket</c> writes. Bitbucket reads one file,
/// <c>bitbucket-pipelines.yml</c>, and has no include of a file in the same repository: when the repository already has one,
/// <c>init</c> leaves it alone and writes the same content to <see cref="FragmentPath"/> for a person to merge in.
/// </summary>
internal static class BitbucketPipelinesTemplate
{
    public const string Path = "bitbucket-pipelines.yml";

    /// <summary>Where the pipeline goes when <see cref="Path"/> exists; inside <c>.lockflight/</c>, so it is protected too.</summary>
    public const string FragmentPath = ".lockflight/ci/bitbucket-pipelines.yml";

    private const int ScriptIndent = 12;

    private const string FindBase = """
        PULL_REQUEST="${BITBUCKET_PR_DESTINATION_BRANCH:-}"
        if [ -n "$PULL_REQUEST" ]; then
          git fetch origin "+refs/heads/$PULL_REQUEST:refs/remotes/origin/$PULL_REQUEST"
          BASE=$(git merge-base HEAD "origin/$PULL_REQUEST")
        else
          BASE=$(git rev-parse --verify --quiet 'HEAD^' || true)
        fi
        """;

    private const string PullRequestPipelines = """
        pipelines:
          pull-requests:
            '**':
              - step: *lockflight-gates
          branches:
            main:
              - step: *lockflight-gates
        """;

    private const string ManualPipelines = """
        # Runs only when started by hand (Pipelines → Run pipeline → custom: lockflight-gates), written by
        # `lockflight init --ci manual`. To judge every pull request, replace this block with pull-requests ('**') and
        # branches (main) pipelines that run the same step.
        pipelines:
          custom:
            lockflight-gates:
              - step: *lockflight-gates
        """;

    private const string PreviewPipelines = """
        # CI during the preview: this project pins a development build of the engine (built from source by
        # scripts/dev-install.sh), which no package feed has, so the engine install below cannot pass yet and `lockflight init`
        # made this pipeline run only when started by hand. Once the project pins a published release, replace this block with
        # pull-requests ('**') and branches (main) pipelines that run the same step.
        pipelines:
          custom:
            lockflight-gates:
              - step: *lockflight-gates
        """;

    private const string Template = """
        # Lockflight gates for Bitbucket Pipelines — generated by `lockflight init --ci-platform bitbucket`. The engine version and
        # policy come from the destination branch on pull requests, so a PR cannot loosen the checks that judge it. Make a
        # successful build a merge check (it blocks only on Bitbucket Premium) and route this file to a default reviewer.
        # Not yet verified on a live Bitbucket workspace: check the first run. See docs/guides/ci-other-platforms.md in the
        # Lockflight repository.
        clone:
          depth: full

        definitions:
          steps:
            - step: &lockflight-gates
                name: lockflight-gates
                image: {SdkImage}
                script:
                  - |
        {Script}
                artifacts:
                  - {ResultDirectory}/**

        {Pipelines}

        """;

    /// <summary>The pipeline with its trigger; the SDK image gets every other .NET channel given.</summary>
    public static string Pipeline(IReadOnlyList<string> dotnetChannels, CiTrigger trigger, bool developmentPin) =>
        Template
            .Replace("{SdkImage}", CiShellScripts.SdkImage, StringComparison.Ordinal)
            .Replace("{Script}", CiShellScripts.Indent(CiShellScripts.ContainerJob(FindBase, dotnetChannels), ScriptIndent), StringComparison.Ordinal)
            .Replace("{ResultDirectory}", CiShellScripts.ResultDirectory, StringComparison.Ordinal)
            .Replace("{Pipelines}", Pipelines(trigger, developmentPin), StringComparison.Ordinal);

    private static string Pipelines(CiTrigger trigger, bool developmentPin) => trigger switch
    {
        CiTrigger.Manual when developmentPin => PreviewPipelines,
        CiTrigger.Manual => ManualPipelines,
        _ => PullRequestPipelines,
    };
}
