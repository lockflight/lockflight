using System.Text.Json;
using System.Text.Json.Nodes;
using Lockflight.Cli.Config;
using Lockflight.Cli.Init;

namespace Lockflight.Cli.Adoption;

/// <summary>
/// Reads an existing Claude Code and Spec Kit setup — the project's and every unit's settings, the user's own hooks (read only),
/// skills, agents, commands, Spec Kit, features, <c>CLAUDE.md</c>, and directories that look like units — into an adoption plan.
/// Reading only: nothing is changed.
/// </summary>
internal static class SetupInventory
{
    /// <summary>The Spec Kit skill the Lockflight preset regenerates (its <c>speckit.tasks</c> command, strategy append).</summary>
    private const string PresetOwnedSkill = "speckit-tasks";

    /// <summary>The Spec Kit version the Lockflight preset is generated from (the init skill and doctor install this one).</summary>
    public const string PinnedSpecKitVersion = "1.1.3";

    /// <summary>Root <c>CLAUDE.md</c> budget in tokens: it is loaded into every session.</summary>
    public const int ClaudeMdTokenBudget = 8000;

    private static readonly string[] LockflightSkills = ["approve", "doctor", "feature", "gate", "init", "review", "status"];

    public static AdoptionPlan Build(string root, Manifest? manifest, string? userHome, DateTimeOffset at)
    {
        List<AdoptionItem> items = [];
        IReadOnlyList<Unit> units = manifest?.Units ?? [];

        List<ClaudeHook> hooks = [.. HookInventory.Read(Path.Combine(root, ".claude", "settings.json"), "shell", root)];
        foreach (Unit unit in units)
        {
            string unitDirectory = Path.Combine(root, unit.Path);
            hooks.AddRange(HookInventory.Read(Path.Combine(unitDirectory, ".claude", "settings.json"), unit.Path, unitDirectory));
        }

        if (userHome is not null)
        {
            hooks.AddRange(HookInventory.Read(Path.Combine(userHome, ".claude", "settings.json"), "user", root));
        }

        // Lockflight's own native hooks (init --native) are not the team's to adopt.
        items.AddRange(hooks.Where(hook => !NativeHooks.IsLockflights(hook.Command)).Select(hook => HookClassifier.Classify(hook, hook.ScriptPath is null ? null : File.ReadAllText(hook.ScriptPath))));
        items.AddRange(Skills(root));
        items.AddRange(Named(root, "agents", "*.md", AdoptionArea.Agent, name => name.Contains("review", StringComparison.OrdinalIgnoreCase)
            ? (AdoptionAction.Flag, "a reviewer agent: advisory next to 'lockflight review', the review of record (evidence-bound)")
            : (AdoptionAction.Keep, "kept; protected from the agent (.claude/agents/**)")));
        items.AddRange(Named(root, "commands", "*.md", AdoptionArea.Command, _ => (AdoptionAction.Keep, "kept; protected from the agent (.claude/commands/**)")));
        if (SpecKit(root) is AdoptionItem specKit)
        {
            items.Add(specKit);
        }

        items.AddRange(Features(root));
        items.Add(ClaudeMd(root));
        items.AddRange(UnitCandidates(root, units));
        return new AdoptionPlan(root, at, items);
    }

    private static IEnumerable<AdoptionItem> Skills(string root)
    {
        string skills = Path.Combine(root, ".claude", "skills");
        if (!Directory.Exists(skills))
        {
            yield break;
        }

        string? newer = SpecKitUpgrade.InstalledVersion(root) is string installed && SpecKitUpgrade.IsNewerThanPinned(installed) ? installed : null;
        foreach (string name in Directory.EnumerateDirectories(skills).Select(Path.GetFileName).OfType<string>().Order(StringComparer.Ordinal))
        {
            yield return name == PresetOwnedSkill
                ? new AdoptionItem(AdoptionArea.Skill, name, AdoptionAction.Upgrade, $"regenerated by the Lockflight preset (stock /speckit-tasks from Spec Kit {PinnedSpecKitVersion} plus Lockflight's rules): your own changes to it are not kept; git has them")
                : name.StartsWith("speckit-", StringComparison.Ordinal) && newer is not null
                ? new AdoptionItem(AdoptionArea.Skill, name, AdoptionAction.Keep, $"a Spec Kit skill from your Spec Kit {newer}: kept as it is")
                : name == PresetOwnedSkill
                ? new AdoptionItem(AdoptionArea.Skill, name, AdoptionAction.Upgrade, $"regenerated by the Lockflight preset (stock /speckit-tasks from Spec Kit {PinnedSpecKitVersion} plus Lockflight's rules): your own changes to it are not kept; git has them")
                : name.StartsWith("speckit-", StringComparison.Ordinal)
                ? new AdoptionItem(AdoptionArea.Skill, name, AdoptionAction.Upgrade, $"a Spec Kit skill: comes from Spec Kit {PinnedSpecKitVersion} with the Lockflight preset; a customised copy is reported, not overwritten")
                : LockflightSkills.Contains(name, StringComparer.OrdinalIgnoreCase)
                    ? new AdoptionItem(AdoptionArea.Skill, name, AdoptionAction.Flag, $"shares its name with Lockflight's '/lockflight:{name}'; both stay, Lockflight's is namespaced")
                    : new AdoptionItem(AdoptionArea.Skill, name, AdoptionAction.Keep, "the team's own skill: kept, protected from the agent (.claude/skills/**)");
        }
    }

    private static IEnumerable<AdoptionItem> Named(string root, string folder, string pattern, AdoptionArea area, Func<string, (AdoptionAction Action, string Reason)> decide)
    {
        string directory = Path.Combine(root, ".claude", folder);
        if (!Directory.Exists(directory))
        {
            yield break;
        }

        foreach (string name in Directory.EnumerateFiles(directory, pattern).Select(Path.GetFileNameWithoutExtension).OfType<string>().Order(StringComparer.Ordinal))
        {
            (AdoptionAction action, string reason) = decide(name);
            yield return new AdoptionItem(area, name, action, reason);
        }
    }

    private static AdoptionItem? SpecKit(string root)
    {
        string options = Path.Combine(root, ".specify", "init-options.json");
        if (!Directory.Exists(Path.Combine(root, ".specify")))
        {
            return null;
        }

        string version = "unknown";
        try
        {
            version = JsonNode.Parse(File.ReadAllText(options))?["speckit_version"]?.GetValue<string>() ?? version;
        }
        catch (Exception exception) when (exception is JsonException or InvalidOperationException or IOException)
        {
            // An unknown version is reported as such.
        }

        bool presetInstalled = File.Exists(Path.Combine(root, ".specify", "presets", ".registry"))
            && File.ReadAllText(Path.Combine(root, ".specify", "presets", ".registry")).Contains("\"lockflight\"", StringComparison.Ordinal);
        if (SpecKitUpgrade.IsNewerThanPinned(version))
        {
            // Merging the pinned stock over a newer install would replace its files with older ones: a downgrade.
            return presetInstalled
                ? new AdoptionItem(AdoptionArea.SpecKit, $"Spec Kit {version}", AdoptionAction.Keep, $"newer than {PinnedSpecKitVersion}, with the Lockflight preset: kept as it is")
                : new AdoptionItem(AdoptionArea.SpecKit, $"Spec Kit {version}", AdoptionAction.Add,
                    $"newer than {PinnedSpecKitVersion}, the version Lockflight's preset is generated from: kept as it is, not downgraded; init --speckit-preset installs only the Lockflight preset (it needs Spec Kit {PinnedSpecKitVersion} or later)");
        }

        return new AdoptionItem(AdoptionArea.SpecKit, $"Spec Kit {version}", presetInstalled && version == PinnedSpecKitVersion ? AdoptionAction.Keep : AdoptionAction.Upgrade,
            presetInstalled && version == PinnedSpecKitVersion
                ? "already the pinned version with the Lockflight preset"
                : $"init --speckit-preset upgrades it to Spec Kit {PinnedSpecKitVersion} with the Lockflight preset; the constitution and every customised template, script or skill are kept and listed");
    }

    private static IEnumerable<AdoptionItem> Features(string root)
    {
        string specs = Path.Combine(root, "specs");
        if (!Directory.Exists(specs))
        {
            yield break;
        }

        string[] features = [.. Directory.EnumerateDirectories(specs).Select(Path.GetFileName).OfType<string>().Order(StringComparer.Ordinal)];
        HashSet<string> sharedNumbers = [.. features.Select(Number).Where(number => number.Length > 0).GroupBy(number => number).Where(group => group.Count() > 1).Select(group => group.Key)];
        foreach (string feature in features)
        {
            string note = sharedNumbers.Contains(Number(feature)) ? " (shares its number with another feature; harmless: the whole folder name is the id)" : string.Empty;
            yield return new AdoptionItem(AdoptionArea.Feature, feature, AdoptionAction.Mark, $"predates Lockflight: no approvals or red/green evidence required (marked by the init that creates the manifest){note}");
        }
    }

    private static string Number(string feature) => new([.. feature.TakeWhile(char.IsDigit)]);

    private static AdoptionItem ClaudeMd(string root)
    {
        string path = Path.Combine(root, "CLAUDE.md");
        bool exists = File.Exists(path);
        string text = exists ? File.ReadAllText(path) : string.Empty;
        if (string.IsNullOrWhiteSpace(text))
        {
            return new AdoptionItem(AdoptionArea.ClaudeMd, "CLAUDE.md", AdoptionAction.Add, exists
                ? "the file is empty; a short Lockflight block is added"
                : "there is none yet; it is created with a short Lockflight block");
        }

        int tokens = Math.Max(1, text.Length / 4);
        string size = $"about {tokens} {(tokens == 1 ? "token" : "tokens")} of the {ClaudeMdTokenBudget} budget";
        return ClaudeMdBlock.IsCurrent(text)
            ? new AdoptionItem(AdoptionArea.ClaudeMd, "CLAUDE.md", AdoptionAction.Keep, $"already has the Lockflight block; {size}")
            : ClaudeMdBlock.IsPresent(text)
            ? new AdoptionItem(AdoptionArea.ClaudeMd, "CLAUDE.md", AdoptionAction.Upgrade, $"the Lockflight block is replaced by the current one; the rest is kept; {size}")
            : new AdoptionItem(AdoptionArea.ClaudeMd, "CLAUDE.md", AdoptionAction.Add, $"a short Lockflight block is added; the rest is kept; {size}{(tokens > ClaudeMdTokenBudget ? " — over budget, consider moving detail into skills" : string.Empty)}");
    }

    /// <summary>Directories that look like units (<see cref="UnitDiscovery"/>) that no unit lists.</summary>
    private static IEnumerable<AdoptionItem> UnitCandidates(string root, IReadOnlyList<Unit> units) =>
        UnitDiscovery.Find(root)
            .Where(candidate => !units.Any(unit => unit.Path.Equals(candidate.Path, StringComparison.OrdinalIgnoreCase)))
            .Select(candidate => new AdoptionItem(AdoptionArea.Unit, candidate.Path, AdoptionAction.Add,
                $"added to units: ({(candidate.DotnetSolution ? ".NET" : "kind: none until a stack adapter covers it")}{(candidate.OwnRepository ? ", its own repository" : string.Empty)})"));
}
