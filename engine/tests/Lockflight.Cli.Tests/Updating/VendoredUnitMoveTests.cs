using Lockflight.Cli.Config;
using Lockflight.Cli.Hosting;
using Lockflight.Cli.Init;
using Lockflight.Cli.Linking;
using Lockflight.Cli.Processes;

namespace Lockflight.Cli.Tests.Updating;

/// <summary>A unit repository with the policy the removed <c>workspace sync</c> vendored: <c>update --project</c> moves it to the shell pointer.</summary>
public sealed class VendoredUnitMoveTests : IDisposable
{
    private const string ShellUrl = "https://example.com/acme/shell.git";

    private const string VendoredPolicy = "# Generated by `lockflight workspace sync` from the workspace shell at abc. Do not edit.\nversion: 1\nprotected: []\n";

    private readonly DirectoryInfo shell = Directory.CreateTempSubdirectory("lockflight-vendored-");

    private readonly DirectoryInfo home = Directory.CreateTempSubdirectory("lockflight-home-");

    private string Orders => Path.Combine(shell.FullName, "services", "orders");

    private string Workflow => Path.Combine(Orders, Templates.WorkflowPath.Replace('/', Path.DirectorySeparatorChar));

    [Fact]
    public async Task AVendoredUnitInsideItsShellMovesToThePointer()
    {
        await CreateWorkspaceAsync(withOrigin: true);

        (ExitCode exitCode, string output, string error) = await UpdateAsync(Orders);

        Assert.True(exitCode == ExitCode.Pass, error);
        Assert.False(File.Exists(Path.Combine(Orders, Manifest.UnitFileName)));
        Manifest unit = ManifestLocator.Discover(Orders).Manifest!;
        Assert.Equal(Orders, unit.Root);
        Assert.Equal(new ShellSettings(ShellUrl, Ref: null, "services/orders"), unit.Shell);
        string workflow = File.ReadAllText(Workflow);
        Assert.Contains("shell-clone: \"true\"", workflow, StringComparison.Ordinal);
        Assert.False(JudgeWorkflowMigration.IsVendoredUnitWorkflow(workflow));
        Assert.Contains("Moved to the shell pointer", output, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ADryRunNamesTheMoveAndWritesNothing()
    {
        await CreateWorkspaceAsync(withOrigin: true);

        (ExitCode exitCode, string output, _) = await UpdateAsync(Orders, "--dry-run");

        Assert.Equal(ExitCode.Pass, exitCode);
        Assert.Contains($"update would delete {Manifest.UnitFileName} and {Templates.WorkflowPath}", output, StringComparison.Ordinal);
        Assert.Contains($"init --unit-of {ShellUrl} --unit-path services/orders", output, StringComparison.Ordinal);
        Assert.Equal(VendoredPolicy, File.ReadAllText(Path.Combine(Orders, Manifest.UnitFileName)));
        Assert.False(File.Exists(Path.Combine(Orders, Manifest.FileName)));
    }

    [Fact]
    public async Task AVendoredUnitOutsideItsShellIsRefusedWithTheManualStep()
    {
        await CreateWorkspaceAsync(withOrigin: true);
        File.Delete(Path.Combine(shell.FullName, Manifest.FileName));

        (ExitCode exitCode, _, string error) = await UpdateAsync(Orders);

        Assert.Equal(ExitCode.Config, exitCode);
        Assert.Contains("init --unit-of <shell url> --unit-path <path>", error, StringComparison.Ordinal);
        Assert.Contains("nothing was changed", error, StringComparison.Ordinal);
        Assert.True(File.Exists(Path.Combine(Orders, Manifest.UnitFileName)));
    }

    [Fact]
    public async Task AShellWithoutAnOriginIsRefusedBecauseTheUnitCouldNotCloneIt()
    {
        await CreateWorkspaceAsync(withOrigin: false);

        (ExitCode exitCode, _, string error) = await UpdateAsync(Orders);

        Assert.Equal(ExitCode.Config, exitCode);
        Assert.Contains("has no origin remote", error, StringComparison.Ordinal);
        Assert.True(File.Exists(Workflow));
    }

    [Fact]
    public async Task AShellStillOnVersion1IsNamedAsTheStepToTakeFirst()
    {
        await CreateWorkspaceAsync(withOrigin: true);
        File.WriteAllText(Path.Combine(shell.FullName, Manifest.FileName), "version: 1\nunits:\n  - path: services/orders\n");

        (ExitCode exitCode, _, string error) = await UpdateAsync(Orders);

        Assert.Equal(ExitCode.Config, exitCode);
        Assert.Contains("is still version 1", error, StringComparison.Ordinal);
        Assert.Contains("migrate the shell first", error, StringComparison.Ordinal);
        Assert.Equal(VendoredPolicy, File.ReadAllText(Path.Combine(Orders, Manifest.UnitFileName)));
    }

    [Fact]
    public async Task AHandEditedUnitWorkflowIsLeftAndNamed()
    {
        await CreateWorkspaceAsync(withOrigin: true);
        File.WriteAllText(Workflow, "# edited by hand\njobs:\n  gates:\n    steps:\n      - run: lockflight gate run --profile pr\n");

        (ExitCode exitCode, string output, string error) = await UpdateAsync(Orders);

        Assert.True(exitCode == ExitCode.Pass, error);
        Assert.Contains($"note: {Templates.WorkflowPath} was edited by hand", output, StringComparison.Ordinal);
        Assert.StartsWith("# edited by hand", File.ReadAllText(Workflow), StringComparison.Ordinal);
    }

    [Fact]
    public async Task AnInitThatStopsWithAnErrorPutsTheDeletedFilesBack()
    {
        await CreateWorkspaceAsync(withOrigin: true);
        Directory.CreateDirectory(Path.Combine(Orders, Manifest.FileName));

        (ExitCode exitCode, _, string error) = await UpdateAsync(Orders);

        Assert.NotEqual(ExitCode.Pass, exitCode);
        Assert.Contains("init stopped with an error, so", error, StringComparison.Ordinal);
        Assert.Equal(VendoredPolicy, File.ReadAllText(Path.Combine(Orders, Manifest.UnitFileName)));
        Assert.True(File.Exists(Workflow));
    }

    [Fact]
    public async Task UpdatingAPointerUnitInsideAVersion1ShellWarnsToMigrateTheShellFirst()
    {
        await CreateWorkspaceAsync(withOrigin: true);
        File.WriteAllText(Path.Combine(shell.FullName, Manifest.FileName), "version: 1\nunits:\n  - path: services/orders\n");
        File.Delete(Path.Combine(Orders, Manifest.UnitFileName));
        File.WriteAllText(Path.Combine(Orders, Manifest.FileName), $"version: 2\nshell:\n  url: {ShellUrl}\n  unit: services/orders\n");

        (_, _, string error) = await UpdateAsync(Orders, "--dry-run");

        Assert.Contains($"warning: the workspace shell at {shell.FullName} still has a version 1 {Manifest.FileName}", error, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("workspace", "sync")]
    [InlineData("workspace", "sync", "--check")]
    public async Task TheRemovedSyncCommandNamesItsReplacementInOneLine(params string[] args)
    {
        (ExitCode exitCode, string output, string error) = await TestConsole.RunAsync(args, string.Empty, shell.FullName);

        Assert.Equal(ExitCode.Config, exitCode);
        Assert.Empty(output);
        Assert.Single(error.Trim().Split('\n'));
        Assert.Contains("workspace sync was removed", error, StringComparison.Ordinal);
        Assert.Contains("update --project", error, StringComparison.Ordinal);
        Assert.Contains("init --unit-of", error, StringComparison.Ordinal);
    }

    [Fact]
    public async Task TheVendoredFileIsNoLongerReadAsAManifest()
    {
        Directory.CreateDirectory(Orders);
        File.WriteAllText(Path.Combine(Orders, Manifest.UnitFileName), "version: 2\nprotected: []\n");

        Assert.Equal(ManifestLoadStatus.NotFound, ManifestLocator.Discover(Orders).Status);
    }

    public void Dispose()
    {
        TempDirectories.DeleteRecursively(shell);
        TempDirectories.DeleteRecursively(home);
    }

    private async Task CreateWorkspaceAsync(bool withOrigin)
    {
        File.WriteAllText(Path.Combine(shell.FullName, Manifest.FileName), "version: 2\nunits:\n  - path: services/orders\n");
        File.WriteAllText(Path.Combine(shell.FullName, ".gitignore"), "services/\n");
        await GitAsync(shell.FullName, ["init", "-q"]);
        if (withOrigin)
        {
            await GitAsync(shell.FullName, ["remote", "add", "origin", ShellUrl]);
        }

        Directory.CreateDirectory(Path.GetDirectoryName(Workflow)!);
        File.WriteAllText(Path.Combine(Orders, Manifest.UnitFileName), VendoredPolicy);
        File.WriteAllText(Workflow, Templates.UnitWorkflow(["10.0.x"]));
        await GitAsync(Orders, ["init", "-q"]);
    }

    private async Task<(ExitCode ExitCode, string Output, string Error)> UpdateAsync(string directory, params string[] options)
    {
        string engine = Path.Combine(home.FullName, "lockflight-native");
        File.WriteAllText(engine, "native engine");
        using StringWriter output = new();
        using StringWriter error = new();
        CliContext context = new(new StringReader(string.Empty), output, error, directory, TimeProvider.System)
        {
            Environment = EnvironmentReader.Of(new Dictionary<string, string> { [EnvironmentVariables.Home] = home.FullName }),
            Engine = new RunningEngine(engine, IsSingleFile: true),
        };

        ExitCode exitCode = await CliApplication.RunAsync(["update", "--project", .. options], context, TestContext.Current.CancellationToken);
        return (exitCode, output.ToString().Trim(), error.ToString().Trim());
    }

    private static Task<ProcessResult> GitAsync(string directory, string[] arguments) =>
        ProcessRunner.RunAsync("git", arguments, directory, TestContext.Current.CancellationToken);
}
