using Lockflight.Cli.Review;

namespace Lockflight.Cli.Tests.Review;

public sealed class EfGeneratedCodeTests
{
    [Fact]
    public void AMigrationDesignerAsEfWritesItLooksGenerated() =>
        Assert.True(EfGeneratedCode.IsMigrationDesigner(EfSamples.Designer));

    [Fact]
    public void AModelSnapshotAsEfWritesItLooksGenerated() =>
        Assert.True(EfGeneratedCode.IsModelSnapshot(EfSamples.Snapshot));

    [Fact]
    public void AFileWithABomAndWindowsLineEndingsStillLooksGenerated() =>
        Assert.True(EfGeneratedCode.IsModelSnapshot("﻿" + EfSamples.Snapshot.ReplaceLineEndings("\r\n")));

    [Fact]
    public void ADesignerIsNotASnapshotAndASnapshotIsNotADesigner()
    {
        Assert.False(EfGeneratedCode.IsModelSnapshot(EfSamples.Designer));
        Assert.False(EfGeneratedCode.IsMigrationDesigner(EfSamples.Snapshot));
    }

    [Fact]
    public void AFileWithoutTheAutoGeneratedHeaderDoesNotLookGenerated() =>
        Assert.False(EfGeneratedCode.IsMigrationDesigner(EfSamples.Designer.Replace("// <auto-generated />", "// generated", StringComparison.Ordinal)));

    [Fact]
    public void AMigrationWithTheHeaderDoesNotLookLikeADesigner() =>
        Assert.False(EfGeneratedCode.IsMigrationDesigner("// <auto-generated />\n" + EfSamples.Migration));

    [Theory]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(\"Id\");\n                    System.IO.File.Delete(\"orders.db\");")]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(\"Id\"); Payments.Refund(\"all\");")]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(Secrets.Leak());")]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(\"Id\").Run();")]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(\"Id\");\n                    var total = Prices.Sum();")]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(\"Id\"); global::System.Environment.Exit(1);")]
    [InlineData("b.HasKey(\"Id\");", "b.HasComment($\"{Secrets.Leak()}\");")]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(\"Id\");\n                    Orders.Ship();")]
    [InlineData("b.HasKey(\"Id\");", "b.HasKey(\"Id\");\n                    x => Prices.Sum();")]
    [InlineData("b.HasKey(\"Id\");", "b.HasData(new { Id = Prices.Count });")]
    [InlineData("Id = 1,", "Id = Prices.Count(),")]
    [InlineData("partial class AddOrders", "partial class AddOrders\n            {\n                public static void Ship() { }\n            }\n            partial class Other")]
    [InlineData("/// <inheritdoc />", "public static int Count => Prices.Sum();")]
    [InlineData("using Shop.Data;", "using static Shop.Payments;")]
    [InlineData("partial class AddOrders", "partial class AddOrders : Migration")]
    public void ADesignerWithCodeBesidesModelBuildingDoesNotLookGenerated(string original, string disguised) =>
        Assert.False(EfGeneratedCode.IsMigrationDesigner(EfSamples.Designer.Replace(original, disguised, StringComparison.Ordinal)));

    [Fact]
    public void ASnapshotWithASecondMethodDoesNotLookGenerated() =>
        Assert.False(EfGeneratedCode.IsModelSnapshot(EfSamples.Snapshot.Replace(
            "protected override void BuildModel(ModelBuilder modelBuilder)",
            "protected override void BuildTargetModel(ModelBuilder modelBuilder)\n{\n}\nprotected override void BuildModel(ModelBuilder modelBuilder)",
            StringComparison.Ordinal)));

    [Fact]
    public void CodeInsideAStringOrCommentDoesNotStopAFileLookingGenerated() =>
        Assert.True(EfGeneratedCode.IsMigrationDesigner(EfSamples.Designer.Replace(
            "b.HasIndex(\"Customer\");", "b.HasIndex(\"Customer\").HasFilter(\"Delete(x) IS NOT NULL\"); // Run()", StringComparison.Ordinal)));
}
