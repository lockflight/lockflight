using Lockflight.Cli.Config;
using Lockflight.Cli.Gates;
using Lockflight.Cli.Gates.Baselines;
using Lockflight.Cli.Gates.Steps;
using Lockflight.Cli.Processes;

namespace Lockflight.Cli.Tests.Gates.Steps;

/// <summary>The suppressions step over a scratch git repository: what an added line silences, against the last commit or a base ref.</summary>
public sealed class SuppressionsStepTests : IDisposable
{
    private const string Order = "namespace Shop;\n\npublic sealed class Order\n{\n    public int Total() => 1;\n}\n";

    private const string MigrationDesigner = """
        // <auto-generated />
        using Microsoft.EntityFrameworkCore;
        using Microsoft.EntityFrameworkCore.Migrations;
        using Shop;

        #nullable disable

        namespace Shop.Migrations
        {
            [DbContext(typeof(ShopContext))]
            [Migration("20260101000000_Init")]
            partial class Init
            {
                protected override void BuildTargetModel(ModelBuilder modelBuilder)
                {
                    modelBuilder.HasAnnotation("ProductVersion", "10.0.0");
                }
            }
        }

        """;

    private readonly DirectoryInfo repository = Directory.CreateTempSubdirectory("lockflight-suppressions-");

    [Fact]
    public async Task AnAddedPragmaFailsWithItsFileLineAndRule()
    {
        await InitRepositoryAsync();
        Write("src/Order.cs", Order.Replace("public sealed", "#pragma warning disable CA1822\npublic sealed", StringComparison.Ordinal));

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Fail, step.Verdict);
        Assert.StartsWith("1 new suppressions: src/Order.cs:3 CA1822 (#pragma warning disable);", step.Detail, StringComparison.Ordinal);
        Assert.Contains("/lockflight:baseline suppressions", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task EveryKindInAnUntrackedFileIsListed()
    {
        await InitRepositoryAsync();
        Write("src/Extra.cs", "#nullable disable\n[ExcludeFromCodeCoverage]\n[SuppressMessage(\"Design\", \"CA1062:Validate\")]\nclass Extra { }\n");
        Write("src/Extra.csproj", "<Project>\n  <PropertyGroup>\n    <NoWarn>$(NoWarn);CS1591</NoWarn>\n    <WarningsNotAsErrors>CA2007</WarningsNotAsErrors>\n  </PropertyGroup>\n</Project>\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Fail, step.Verdict);
        Assert.Contains("5 new suppressions", step.Detail, StringComparison.Ordinal);
        Assert.Contains("src/Extra.cs:1 nullable (#nullable disable)", step.Detail, StringComparison.Ordinal);
        Assert.Contains("src/Extra.cs:2 ExcludeFromCodeCoverage ([ExcludeFromCodeCoverage])", step.Detail, StringComparison.Ordinal);
        Assert.Contains("src/Extra.cs:3 CA1062 ([SuppressMessage])", step.Detail, StringComparison.Ordinal);
        Assert.Contains("src/Extra.csproj:3 CS1591 (<NoWarn>)", step.Detail, StringComparison.Ordinal);
        Assert.Contains("src/Extra.csproj:4 CA2007 (<WarningsNotAsErrors>)", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ASuppressionAlreadyInTheCodeIsNotJudged()
    {
        Write("src/Order.cs", "#pragma warning disable CA1822\n" + Order);
        await InitRepositoryAsync();
        Write("src/Order.cs", "#pragma warning disable CA1822\n" + Order.Replace("=> 1", "=> 2", StringComparison.Ordinal));

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Pass, step.Verdict);
        Assert.Equal("1 changed files checked; uncommitted changes checked (pass --base to check the branch's commits)", step.Detail);
    }

    [Fact]
    public async Task AChangeWithoutCodeBuildOrAnalyzerFilesIsNotApplicable()
    {
        await InitRepositoryAsync();
        Write("README.md", "#pragma warning disable CA1822\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.NotApplicable, step.Verdict);
        Assert.Equal("no changed C#, MSBuild or analyzer config files", step.Detail);
    }

    [Fact]
    public async Task ASuppressionMovedWithinItsFileIsNotNew()
    {
        Write("src/Order.cs", "#pragma warning disable CA1822\n" + Order);
        await InitRepositoryAsync();
        Write("src/Order.cs", Order + "#pragma warning disable CA1822\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Pass, step.Verdict);
    }

    [Fact]
    public async Task WithABaseTheBranchsCommitsAreJudged()
    {
        await InitRepositoryAsync();
        await GitAsync(["branch", "base"]);
        Write("src/Order.cs", "#nullable disable\n" + Order);
        await CommitAsync("disable nullable");

        GateStep withoutBase = await RunStepAsync(GateMode.Fail);
        GateStep withBase = await RunStepAsync(GateMode.Fail, baseRef: "base");

        Assert.Equal(Verdict.NotApplicable, withoutBase.Verdict);
        Assert.Equal(Verdict.Fail, withBase.Verdict);
        Assert.Contains("src/Order.cs:1 nullable", withBase.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ARuleAcceptedForAFileInTheBaselinePassesAndAnyOtherStillFails()
    {
        await InitRepositoryAsync();
        Write("src/Order.cs", "#pragma warning disable CA1822\n" + Order);
        Write("src/Line.cs", "#pragma warning disable CA1822\nclass Line { }\n");
        new AcceptedSuppressions(repository.FullName).Save(["src/Order.cs|CA1822"]);

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Fail, step.Verdict);
        Assert.StartsWith("1 new suppressions: src/Line.cs:1 CA1822", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task AnAcceptedSuppressionIsCountedOnThePass()
    {
        await InitRepositoryAsync();
        Write("src/Order.cs", "#pragma warning disable CA1822\n" + Order);
        new AcceptedSuppressions(repository.FullName).Save(["src/Order.cs|CA1822"]);

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Pass, step.Verdict);
        Assert.Contains("1 added suppressions accepted by .lockflight/baselines/suppressions.json", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task TheNullableDisableEfCoreWritesInAMigrationIsNotJudgedButAPragmaThereIs()
    {
        await InitRepositoryAsync();
        Write("src/Migrations/20260101000000_Init.Designer.cs", MigrationDesigner);
        Write("src/Migrations/20260101000000_Init.cs", "using Microsoft.EntityFrameworkCore.Migrations;\n\n#nullable disable\n#pragma warning disable CA1062\n\nnamespace Shop.Migrations;\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Fail, step.Verdict);
        Assert.StartsWith("1 new suppressions: src/Migrations/20260101000000_Init.cs:4 CA1062", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ANullableDisableInAMigrationWithAHandWrittenDesignerIsJudged()
    {
        await InitRepositoryAsync();
        Write("src/Migrations/20260101000000_Init.Designer.cs", "class NotGenerated { }\n");
        Write("src/Migrations/20260101000000_Init.cs", "#nullable disable\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Fail, step.Verdict);
        Assert.Contains("_Init.cs:1 nullable", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task AGeneratedMigrationDesignerIsLeftOut()
    {
        await InitRepositoryAsync();
        Write("src/Migrations/20260101000000_Init.Designer.cs", MigrationDesigner);
        Write("src/Migrations/20260101000000_Init.cs", "namespace Shop.Migrations;\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Pass, step.Verdict);
    }

    [Theory]
    [InlineData("error", "none", true)]
    [InlineData("error", "warning", true)]
    [InlineData("none", "silent", false)]
    [InlineData("warning", "error", false)]
    public async Task AnAnalyzerSeverityFailsWhenTheChangeLowersIt(string before, string after, bool fails)
    {
        Write(".editorconfig", $"root = true\n\n[*.cs]\ndotnet_diagnostic.CA2000.severity = {before}\n");
        await InitRepositoryAsync();
        Write(".editorconfig", $"root = true\n\n[*.cs]\ndotnet_diagnostic.CA2000.severity = {after}\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(fails ? Verdict.Fail : Verdict.Pass, step.Verdict);
        if (fails)
        {
            Assert.Contains(".editorconfig:4 CA2000 (lowered severity)", step.Detail, StringComparison.Ordinal);
        }
    }

    [Fact]
    public async Task InReportModeTheFindingsAreShownOnAPass()
    {
        await InitRepositoryAsync();
        Write("src/Order.cs", "#pragma warning disable CA1822\n" + Order);

        GateStep step = await RunStepAsync(GateMode.Report);

        Assert.Equal(Verdict.Pass, step.Verdict);
        Assert.StartsWith("report only (gates.quality.suppressions: report; set it to fail to block): 1 new suppressions: src/Order.cs:1 CA1822", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task TurnedOffTheStepDoesNotRunAndSaysSo()
    {
        await InitRepositoryAsync();
        Write("src/Order.cs", "#pragma warning disable CA1822\n" + Order);

        GateStep step = await RunStepAsync(GateMode.Off);

        Assert.Equal(Verdict.NotApplicable, step.Verdict);
        Assert.Equal("off by manifest (gates.quality.suppressions: off)", step.Detail);
    }

    [Theory]
    [InlineData("fail")]
    [InlineData("report")]
    public async Task OutsideAGitRepositoryTheStepIsAnErrorInEveryMode(string modeName)
    {
        Assert.True(GateModeNames.TryParse(modeName, out GateMode mode));

        GateStep step = await RunStepAsync(mode);

        Assert.Equal(Verdict.Error, step.Verdict);
        Assert.Contains("needs a git repository", step.Detail, StringComparison.Ordinal);
    }

    /// <summary>The canary: a planted suppression is caught, and its harmless twin — the same line in a comment — passes.</summary>
    [Theory]
    [InlineData("#pragma warning disable CA1822\n", true)]
    [InlineData("// #pragma warning disable CA1822\n", false)]
    public async Task CanaryAPlantedSuppressionIsCaughtAndItsHarmlessTwinPasses(string planted, bool caught)
    {
        await InitRepositoryAsync();
        Write("src/Order.cs", planted + Order);

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(caught ? Verdict.Fail : Verdict.Pass, step.Verdict);
    }

    public void Dispose() => TempDirectories.DeleteRecursively(repository);

    private async Task<GateStep> RunStepAsync(GateMode mode, string? baseRef = null)
    {
        GateSettings settings = GateSettings.Default with { Suppressions = mode };
        GateRunContext run = new(repository.FullName, repository.FullName, GateProfile.PullRequest, settings, baseRef, TimeProvider.System);
        return (await new SuppressionsStep().RunAsync(run, GateRunFacts.None, TestContext.Current.CancellationToken)).Step;
    }

    private async Task InitRepositoryAsync()
    {
        await GitAsync(["init", "-q"]);
        Write(".gitignore", ".lockflight/\n");
        if (!File.Exists(Path.Combine(repository.FullName, "src", "Order.cs")))
        {
            Write("src/Order.cs", Order);
        }

        await CommitAsync("init");
    }

    private async Task CommitAsync(string message)
    {
        await GitAsync(["add", "."]);
        await GitAsync(["-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", message]);
    }

    private void Write(string relativePath, string content)
    {
        string path = Path.Combine(repository.FullName, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }

    private Task<ProcessResult> GitAsync(string[] arguments) =>
        ProcessRunner.RunAsync("git", arguments, repository.FullName, TestContext.Current.CancellationToken);
}
