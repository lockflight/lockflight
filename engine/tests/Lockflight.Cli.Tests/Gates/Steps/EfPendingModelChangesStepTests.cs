using Lockflight.Cli.Config;
using Lockflight.Cli.Gates;
using Lockflight.Cli.Gates.Steps;
using Lockflight.Cli.Processes;

namespace Lockflight.Cli.Tests.Gates.Steps;

/// <summary>
/// The EF Core model step over a scratch repository with a migrations project and an API project as its startup project; the .NET
/// SDK is replaced by canned results, so these say which DbContexts are checked, with what, and how each answer is judged.
/// </summary>
public sealed class EfPendingModelChangesStepTests : IDisposable
{
    private const string ToolManifest = """{ "version": 1, "isRoot": true, "tools": { "dotnet-ef": { "version": "10.0.0", "commands": ["dotnet-ef"] } } }""";

    private const string DataProject = """
        <Project Sdk="Microsoft.NET.Sdk">
          <ItemGroup>
            <PackageReference Include="Microsoft.EntityFrameworkCore.SqlServer" Version="10.0.0" />
            <ProjectReference Include="..\Shop.Domain\Shop.Domain.csproj" />
          </ItemGroup>
        </Project>
        """;

    private const string ApiProject = """
        <Project Sdk="Microsoft.NET.Sdk.Web">
          <ItemGroup>
            <PackageReference Include="Microsoft.EntityFrameworkCore.Design" Version="10.0.0" />
            <ProjectReference Include="../Shop.Data/Shop.Data.csproj" />
          </ItemGroup>
        </Project>
        """;

    private const string Snapshot = """
        // <auto-generated />
        namespace Shop.Data.Migrations
        {
            [DbContext(typeof(Shop.Data.ShopContext))]
            partial class ShopContextModelSnapshot : ModelSnapshot
            {
            }
        }
        """;

    private const string PendingOutput = "Build started...\nBuild succeeded.\nChanges have been made to the model since the last migration. Add a new migration.\n";

    private readonly DirectoryInfo repository = Directory.CreateTempSubdirectory("lockflight-ef-");

    private readonly List<string> calls = [];

    private ProcessResult efAnswer = new(0, "No changes have been made to the model since the last migration.\n", string.Empty, 0, TimedOut: false);

    [Fact]
    public async Task AModelChangedWithoutAMigrationFailsAndNamesTheContext()
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Domain/Order.cs", "public sealed class Order { public int Id { get; set; } public string Note { get; set; } = \"\"; }\n");
        efAnswer = new ProcessResult(1, PendingOutput, string.Empty, 0, TimedOut: false);

        GateStep step = await RunStepAsync(GateMode.Auto);

        Assert.Equal(Verdict.Fail, step.Verdict);
        Assert.Equal("1 models changed without a migration: src/Shop.Data/Shop.Data.csproj (ShopContext); add one (dotnet ef migrations add <name>) and commit it with the change", step.Detail);
        Assert.Equal(
            ["dotnet tool restore", "dotnet ef migrations has-pending-model-changes --project src/Shop.Data/Shop.Data.csproj --context ShopContext --startup-project src/Shop.Api/Shop.Api.csproj"],
            calls.Select(call => call.Replace('\\', '/')));
    }

    [Fact]
    public async Task AModelWithItsMigrationPassesAndSaysWhatWasChecked()
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Data/ShopContext.cs", "// changed\n");

        GateStep step = await RunStepAsync(GateMode.Auto);

        Assert.Equal(Verdict.Pass, step.Verdict);
        Assert.Equal("1 DbContexts checked: src/Shop.Data/Shop.Data.csproj (ShopContext)", step.Detail);
    }

    [Fact]
    public async Task WithoutADotnetEfPinTheDefaultDoesNotRunAndSaysHowToForceIt()
    {
        await InitRepositoryAsync(pinned: false);
        Write("src/Shop.Domain/Order.cs", "// changed\n");

        GateStep step = await RunStepAsync(GateMode.Auto);

        Assert.Equal(Verdict.NotApplicable, step.Verdict);
        Assert.Contains("dotnet-ef is not pinned in a tool manifest", step.Detail, StringComparison.Ordinal);
        Assert.Contains("gates.ef.pendingModelChanges: fail", step.Detail, StringComparison.Ordinal);
        Assert.Empty(calls);
    }

    [Fact]
    public async Task FailRunsTheMachinesDotnetEfWithoutAPinAndRestoresNothing()
    {
        await InitRepositoryAsync(pinned: false);
        Write("src/Shop.Domain/Order.cs", "// changed\n");

        GateStep step = await RunStepAsync(GateMode.Fail);

        Assert.Equal(Verdict.Pass, step.Verdict);
        Assert.DoesNotContain("dotnet tool restore", calls);
        Assert.Single(calls);
    }

    [Fact]
    public async Task AChangeOutsideTheEfProjectsIsNotApplicable()
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Api/Program.cs", "// changed\n");
        Write("README.md", "changed\n");

        GateStep step = await RunStepAsync(GateMode.Auto);

        Assert.Equal(Verdict.NotApplicable, step.Verdict);
        Assert.Equal("no change touches an EF Core project (src/Shop.Data/Shop.Data.csproj (ShopContext))", step.Detail);
        Assert.Empty(calls);
    }

    [Fact]
    public async Task WithABaseTheBranchsCommittedChangeCounts()
    {
        await InitRepositoryAsync(pinned: true);
        await GitAsync(["branch", "base"]);
        Write("src/Shop.Domain/Order.cs", "// changed\n");
        await CommitAsync("change the model");

        GateStep withoutBase = await RunStepAsync(GateMode.Auto);
        GateStep withBase = await RunStepAsync(GateMode.Auto, baseRef: "base");

        Assert.Equal(Verdict.NotApplicable, withoutBase.Verdict);
        Assert.Equal(Verdict.Pass, withBase.Verdict);
    }

    [Fact]
    public async Task ARepositoryWithoutMigrationsIsNotApplicable()
    {
        await GitAsync(["init", "-q"]);
        Write("dotnet-tools.json", ToolManifest);
        Write("src/App/App.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n");
        await CommitAsync("init");

        GateStep step = await RunStepAsync(GateMode.Auto);

        Assert.Equal(Verdict.NotApplicable, step.Verdict);
        Assert.Equal("no EF Core migrations (Migrations/*ModelSnapshot.cs) here", step.Detail);
    }

    [Fact]
    public async Task ADotnetEfThatCannotRunIsAnErrorEvenInReportMode()
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Domain/Order.cs", "// changed\n");
        efAnswer = new ProcessResult(1, string.Empty, "Could not execute because the specified command or file was not found.\n", 0, TimedOut: false);

        GateStep step = await RunStepAsync(GateMode.Report);

        Assert.Equal(Verdict.Error, step.Verdict);
        Assert.StartsWith("dotnet ef could not check src/Shop.Data/Shop.Data.csproj (ShopContext): Could not execute", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ACheckThatRunsOutOfTimeIsAnError()
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Domain/Order.cs", "// changed\n");
        efAnswer = new ProcessResult(ProcessRunner.TimedOutExitCode, string.Empty, string.Empty, 2000, TimedOut: true);

        GateStep step = await RunStepAsync(GateMode.Auto);

        Assert.Equal(Verdict.Error, step.Verdict);
        Assert.Contains("timed out", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task InReportModeAPendingChangeIsShownOnAPass()
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Domain/Order.cs", "// changed\n");
        efAnswer = new ProcessResult(1, PendingOutput, string.Empty, 0, TimedOut: false);

        GateStep step = await RunStepAsync(GateMode.Report);

        Assert.Equal(Verdict.Pass, step.Verdict);
        Assert.StartsWith("report only (gates.ef.pendingModelChanges: report; set it to fail to block): 1 models changed", step.Detail, StringComparison.Ordinal);
    }

    [Fact]
    public async Task TurnedOffTheStepRunsNothing()
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Domain/Order.cs", "// changed\n");

        GateStep step = await RunStepAsync(GateMode.Off);

        Assert.Equal(Verdict.NotApplicable, step.Verdict);
        Assert.Equal("off by manifest (gates.ef.pendingModelChanges: off)", step.Detail);
        Assert.Empty(calls);
    }

    /// <summary>The canary: a planted model change without a migration is caught, and its harmless twin — the model unchanged — passes.</summary>
    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public async Task CanaryAPlantedModelChangeIsCaughtAndItsHarmlessTwinPasses(bool planted)
    {
        await InitRepositoryAsync(pinned: true);
        Write("src/Shop.Domain/Order.cs", "// planted\n");
        if (planted)
        {
            efAnswer = new ProcessResult(1, PendingOutput, string.Empty, 0, TimedOut: false);
        }

        GateStep step = await RunStepAsync(GateMode.Auto);

        Assert.Equal(planted ? Verdict.Fail : Verdict.Pass, step.Verdict);
    }

    public void Dispose() => TempDirectories.DeleteRecursively(repository);

    private async Task<GateStep> RunStepAsync(GateMode mode, string? baseRef = null)
    {
        GateSettings settings = GateSettings.Default with { EfPendingModelChanges = mode };
        GateRunContext run = new(repository.FullName, repository.FullName, GateProfile.PullRequest, settings, baseRef, TimeProvider.System)
        {
            Processes = (fileName, arguments, workingDirectory, timeLimit, cancellationToken) =>
            {
                calls.Add($"{fileName} {string.Join(' ', arguments)}");
                return Task.FromResult(arguments[0] == "ef" ? efAnswer : new ProcessResult(0, string.Empty, string.Empty, 0, TimedOut: false));
            },
        };
        return (await new EfPendingModelChangesStep().RunAsync(run, GateRunFacts.None, TestContext.Current.CancellationToken)).Step;
    }

    private async Task InitRepositoryAsync(bool pinned)
    {
        await GitAsync(["init", "-q"]);
        if (pinned)
        {
            Write(".config/dotnet-tools.json", ToolManifest);
        }

        Write("src/Shop.Domain/Shop.Domain.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n");
        Write("src/Shop.Domain/Order.cs", "public sealed class Order { public int Id { get; set; } }\n");
        Write("src/Shop.Data/Shop.Data.csproj", DataProject);
        Write("src/Shop.Data/ShopContext.cs", "public sealed class ShopContext { }\n");
        Write("src/Shop.Data/Migrations/ShopContextModelSnapshot.cs", Snapshot);
        Write("src/Shop.Api/Shop.Api.csproj", ApiProject);
        Write("src/Shop.Api/Program.cs", "return;\n");
        await CommitAsync("init");
    }

    private async Task CommitAsync(string message)
    {
        await GitAsync(["add", "-A"]);
        await GitAsync(["-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", message]);
    }

    private void Write(string relativePath, string content)
    {
        string path = Path.Combine(repository.FullName, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }

    private Task<ProcessResult> GitAsync(string[] arguments) =>
        ProcessRunner.RunAsync("git", arguments, repository.FullName, TestContext.Current.CancellationToken);
}
